// Исход красной канарейки: виноват деплой или лежит бэкенд по посторонней
// причине (issue #1426). Одно место правды — и для самой канарейки, и для
// тестов, и для шага автооката.
//
// Чем оплачено. Прогон 35639422589 (deploy-worker.yml, job deploy на 61b185aa,
// слияние PR #1420): гвардия типов пройдена, деплой состоялся, канарейка упала
// по таймауту `waiting for locator('#gate-token')` — и `wrangler rollback`
// откатил КОРРЕКТНЫЙ код. Поле не появилось не из-за деплоя: была исчерпана
// суточная квота rows_read Durable Objects (#1411), любой SELECT в объекте
// бросал исключение, `/api/status` отдавал 500, страница не инициализировалась.
// Статика при этом отдавалась нормально.
//
// Получалось кольцо: фикс исчерпанной квоты нельзя задеплоить, потому что
// квота исчерпана — канарейка упрётся в тот же 500 и откатит фикс.
//
// Признак берётся НЕ из догадки, а из собственного контракта воркера:
// `storageErrorResponse` (cf-worker/src/harness.ts) уже классифицирует отказ
// хранилища через `classifyStorageError` и отдаёт код `storage_quota_exceeded`.
// Канарейка читает готовый код, а не заводит вторую копию правила «похоже на
// квоту» — иначе два правила разошлись бы, как разошлись три копии
// классификации исхода морды (#1433).

/** Прогон зелёный. */
export const EXIT_OK = 0;
/** Деплой плохой — откат оправдан (историческое поведение, не меняется). */
export const EXIT_DEPLOY_BAD = 1;
/** Бэкенд лежит по причине, к деплою не относящейся: прогон обязан упасть
 *  громко, но откатывать нельзя — прежняя версия упрётся в то же самое. */
export const EXIT_BACKEND_DOWN = 3;

/** Код ошибки воркера, означающий исчерпание суточной квоты хранилища DO.
 *  Литерал совпадает с `storageErrorResponse` в cf-worker/src/harness.ts;
 *  расхождение ловит тест canary-outcome.spec.ts, который берёт код из
 *  РЕАЛЬНОГО ответа воркера, а не из этой строки. */
const STORAGE_QUOTA_CODE = "storage_quota_exceeded";

/**
 * Виноват ли деплой в этом ответе `/api/ready`.
 *
 * Возвращает `{ infra, reason }`. `infra: true` — отказ инфраструктурный,
 * откат не поможет; `reason` — ФАКТ для человека, не список гипотез.
 *
 * Консервативно по построению: инфраструктурным считается только тот отказ,
 * который воркер назвал сам своим кодом. Любой другой 5xx остаётся «виноват
 * деплой» — то есть поведение до #1426 сохраняется везде, кроме одного
 * распознанного случая. Обратное умолчание было бы опаснее: сломанный деплой,
 * положивший API, перестал бы откатываться.
 */
export function classifyApiFailure(status, bodyText) {
  let code = null;
  try {
    code = JSON.parse(bodyText ?? "")?.error?.code ?? null;
  } catch {
    code = null; // не наш JSON (например страница Cloudflare) — см. оговорку ниже
  }
  if (status >= 500 && code === STORAGE_QUOTA_CODE) {
    return {
      infra: true,
      reason:
        "суточная квота хранилища Durable Objects исчерпана — воркер назвал это " +
        `сам кодом ${STORAGE_QUOTA_CODE}; откат не поможет: прежняя версия ` +
        "упрётся в ту же квоту (сброс в 00:00 UTC, #1411)",
    };
  }
  return {
    infra: false,
    reason: `/api/ready вернул ${status}: ${(bodyText ?? "").slice(0, 300)}`,
  };
}
