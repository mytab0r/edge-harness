// Исход красной канарейки: виноват деплой или лежит бэкенд по посторонней
// причине (issue #1426). Одно место правды — и для самой канарейки, и для
// тестов, и для шага автооката.
//
// Чем оплачено. Прогон 35639422589 (deploy-worker.yml, job deploy на 61b185aa,
// слияние PR #1420): гвардия типов пройдена, деплой состоялся, канарейка упала
// по таймауту `waiting for locator('#gate-token')` — и `wrangler rollback`
// откатил КОРРЕКТНЫЙ код. Поле не появилось не из-за деплоя: была исчерпана
// суточная квота rows_read Durable Objects (#1411). Живой зонд того же
// периода: `GET /api/status → 500, error code: 1101` при `GET / → 200` —
// статика отдавалась нормально, сам деплой был в порядке. Получалось кольцо:
// фикс исчерпанной квоты нельзя задеплоить, потому что квота исчерпана.
//
// Правило различения — из постановки задачи #1426, по данным, которые зонд и
// так получает:
//   * статика НЕ отдаётся (GET / не 200) — деплой плохой, откат оправдан;
//   * статика отдаётся, а `/api/*` отвечает 5xx — бэкенд лежит по посторонней
//     причине, откат НЕ делается: прежняя версия упрётся в тот же отказ.
//     Особенно `error code: 1101` (служебная страница Cloudflare: воркер упал
//     до собственного обработчика) и код/текст квоты DO — оба облика живут
//     при исправной статике. Правило покрывает ЛЮБОЙ 5xx: когда тело ответа
//     называет причину (воркер — кодом storage_quota_exceeded, Cloudflare —
//     страницей 1101), текст отказа называет её фактом; когда не называет —
//     называется сам факт 5xx, без списка гипотез («Алерт не гадает»).

/** Деплой плохой — откат оправдан (историческое поведение, не меняется). */
export const EXIT_DEPLOY_BAD = 1;
/** Бэкенд лежит по причине, к деплою не относящейся: прогон обязан упасть
 *  громко, но откатывать нельзя — прежняя версия упрётся в то же самое. */
export const EXIT_BACKEND_DOWN = 3;
// Код 0 (зелено) явной константы не имеет: успех — это выход без process.exit.

/** Код ошибки воркера при исчерпании суточной квоты хранилища DO. Литерал
 *  совпадает с `storageErrorResponse` (cf-worker/src/harness.ts) — там
 *  единственное место правды; расхождение поймали бы тесты стенда, которые
 *  кормят канарейку прод-формой ответа, а не пересказом. */
const STORAGE_QUOTA_CODE = "storage_quota_exceeded";

/** Служебная страница Cloudflare «error code: 1101» — исключение в воркере
 *  до нашего обработчика. РЕАЛЬНОЕ тело отказа живого случая (#1426). */
const CF_WORKER_EXCEPTION_RE = /\berror code: 1101\b/;

/**
 * Причина отказа API, названная телом ответа, — факт, не гипотеза.
 * null — тело причины не назвало; тогда факт — сам 5xx.
 */
export function apiFailureCause(status, bodyText) {
  let code = null;
  try {
    code = JSON.parse(bodyText ?? "")?.error?.code ?? null;
  } catch {
    code = null; // не наш JSON — например служебная страница Cloudflare
  }
  if (code === STORAGE_QUOTA_CODE) {
    return (
      "суточная квота хранилища Durable Objects исчерпана — воркер назвал " +
      `это сам (код ${STORAGE_QUOTA_CODE}); снимается сбросом в 00:00 UTC (#1411)`
    );
  }
  if (CF_WORKER_EXCEPTION_RE.test(bodyText ?? "")) {
    return (
      "воркер упал до собственного обработчика — Cloudflare отдал служебную " +
      "страницу «error code: 1101»"
    );
  }
  return null;
}

/** Текст отказа «бэкенд лежит»: называется исход и решение, не гипотезы.
 *  Одна копия для обоих мест вызова (зонд до браузера и проверка готовности
 *  после браузера) — вторая копия разошлась бы при следующей правке. */
export function backendDownLines(reason) {
  return [
    `canary-ui: BACKEND-DOWN — ${reason}.`,
    "canary-ui: бэкенд отдаёт 5xx при отдающейся статике — деплой НЕ откатываю: " +
    "прежняя версия упрётся в тот же отказ, а исправление, если оно в этом " +
    "деплое, откат похоронил бы. Прогон остаётся красным.",
  ];
}

/**
 * Исход пары зондов «статика + API», решаемый ДО запуска браузера.
 *
 * Возвращает `{ outcome, reason }`:
 *   - `backend-down` — статика отдаётся (200), а API ответил 5xx: бэкенд
 *     лежит по посторонней причине, откатывать нельзя;
 *   - `deploy-bad` — статика не отдаётся: деплой плохой, откат оправдан;
 *   - `browser` — зонды не дали решения (оба здоровы / сеть не ответила):
 *     решает браузерная часть, поведение до #1426 сохраняется.
 *
 * 5xx от API при НЕ ответившей статике — «деплой плохой»: постановка задачи
 * называет нестатикой вину деплоя. Сетевая ошибка зонда (null) консервативна:
 * решение не принимается, исполнение идёт дальше — как до #1426.
 */
export function probeOutcome(staticStatus, apiStatus, apiBodyText) {
  const apiDown = apiStatus !== null && apiStatus >= 500;
  if (apiDown && staticStatus === 200) {
    const cause = apiFailureCause(apiStatus, apiBodyText);
    return {
      outcome: "backend-down",
      reason:
        cause ??
        `бэкенд отдаёт ${apiStatus} на /api/ready; тело ответа: ` +
        `${(apiBodyText ?? "").trim().slice(0, 300) || "(пусто)"}`,
    };
  }
  if (staticStatus !== null && staticStatus !== 200) {
    return {
      outcome: "deploy-bad",
      reason: `статика не отдаётся: GET / вернул ${staticStatus}`,
    };
  }
  return {
    outcome: "browser",
    reason:
      `статика ${staticStatus === 200 ? "200" : "ответа нет"}, ` +
      `/api/ready ${apiStatus === null ? "ответа нет" : apiStatus}` +
      (apiDown ? "" : ", бэкенд отвечает"),
  };
}
