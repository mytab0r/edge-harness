PIPELINE_STATUS_MARKER_FAMILY_RE = re.compile(r"\[статус конвейера:")


def check_pipeline_status_marker_impersonation(comments: list[dict]) -> list[dict]:
    """`comments` — прод-форма REST-ответа `GET .../issues/{n}/comments`
    ЦЕЛИКОМ (сырые dict'ы с полями `id`/`created_at`/`user`/
    `performed_via_github_app`/`html_url`, без предварительной фильтрации
    вызывающей стороной) — фильтр по семейству маркера и по автору оба
    внутри, тем же приёмом, что и другие check_* этого файла (IO снаружи,
    разбор внутри, см. модульный докстринг).

    Нарушение — комментарий, чья ПЕРВАЯ СТРОКА содержит
    PIPELINE_STATUS_MARKER_FAMILY_RE, и чей `performed_via_github_app` —
    `None` (опубликован НЕ через GitHub App/job-токен). Условие абсолютное
    для найденных так маркеров, без freshness-окна и без сравнения с
    содержимым (в отличие от инварианта 16).

    Проверка ИМЕННО первой строки (не всего тела, находка ревью #1102,
    живые id 5641698169/5651719035, 2026-09-13): все конструкторы этого
    семейства (`scheduler.py`: `f"✅ {WIP_GATE_CLOSE_MARKER}\\n..."`,
    `f"⏸️ {WIP_GATE_OPEN_MARKER}\\n..."`; `pulse_guard.py`: `f"🚨 edge-harness:
    {PAUSE_MARKER}\\n..."` и аналоги) кладут маркер В САМОМ НАЧАЛЕ тела, перед
    первым `\\n` — а вот ПРОЗА, которая ЦИТИРУЕТ/ОБСУЖДАЕТ маркер (ревизия
    пула, объясняющая происхождение `WATCHDOG_ISSUE`; сам разбор инцидента
    #1074, комментарий-опровержение, дословно приводящий текст ложных
    маркеров как улику), несёт ту же подстроку в СЕРЕДИНЕ длинного тела.
    Проверка по всему телу считала бы такую прозу ЕЩЁ ОДНИМ нарушением —
    ложное срабатывание на легитимном обсуждении, найденное живым замером на
    #120 (2 из 176 совпадений подстроки были прозой, не маркером)."""
    violations = []
    for comment in comments:
        body = comment.get("body") or ""
        if not body:
            continue
        first_line = body.splitlines()[0]
        if not PIPELINE_STATUS_MARKER_FAMILY_RE.search(first_line):
            continue
        if comment.get("performed_via_github_app") is not None:
            continue  # опубликовано через GitHub App/job-токен — легитимно
        violations.append({
            "id": comment.get("id"),
            "created_at": comment.get("created_at"),
            "login": (comment.get("user") or {}).get("login"),
            "user_type": (comment.get("user") or {}).get("type"),
            "url": comment.get("html_url"),
        })
    return sorted(violations, key=lambda item: item["created_at"] or "")

