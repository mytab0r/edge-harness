# Эскалирующие инварианты: run_escalations обязана нести ветку для каждого
# номера отсюда — находка доходит до канала владельца (#120 + Telegram через
# pulse_guard.escalate), а не живёт только строкой отчёта прогона. 18 в
# списке — поставленная задача (#1101, находка ревью PR #1102): поддельный
# PAUSE/RESUME — единственный класс этих находок, который не только
# сигнализирует, но и МЕНЯЕТ решение (conveyor_gate читает маркеры #120 без
# trusted_login); соседний 16 эскалирует, а более широкий 18 молчал бы.
# Газ общий и автоматический: escalate_if_new дедуплицирует по множеству id
# нарушителей (вечный долг — одна эскалация, новая подделка — новая), ручного
# снятия не требует.
ESCALATING_INVARIANTS = (1, 3, 12, 15, 16, 17, 18)

def escalate_if_new(repo: str, invariant_id: int, marker_key: str, text: str) -> str | None:
    """Эскалация «один раз на состояние»: маркер кодирует конкретный набор
    нарушителей (не просто факт «инвариант N нарушен») — тот же приём, что
    pulse_guard.PAUSE_MARKER/HEARTBEAT_MARKER (issue_marker_times ищет
    подстроку). Набор изменился (новый нарушитель, старый пропал) — новый
    маркер, новая эскалация; тот же набор — тишина, конвейер не спамит
    Telegram каждые 15 минут одним и тем же списком."""
    marker = f"[инвариант {invariant_id}: {marker_key}]"
    try:
        if issue_marker_times(repo, WATCHDOG_ISSUE, marker):
            return None  # уже эскалировано именно это состояние
    except RuntimeError as error:
        print(f"::warning::не удалось прочитать маркеры #{WATCHDOG_ISSUE}: {error}", file=sys.stderr)
        return None
    return escalate(repo, WATCHDOG_ISSUE, f"{marker}\n{text}")


def pipeline_status_marker_key(violations: list[dict]) -> str:
    """Компактный дедуп-ключ эскалации инварианта 18: хэш сортированного
    множества id нарушителей. Полный перечень id в маркере (первая версия)
    умирал о Telegram-плечо: лимит Bot API — 4096 символов на сообщение,
    нарезки длинных текстов в send_telegram нет, переполнение — «НЕ
    доставлен» при зелёном прогоне (блокирующая находка ревью PR #1102,
    третий раунд: при 174 нарушителях текст уже 2569 символов, темп
    писателя ~25/сутки — лимит через дни). Хэш ловит ЛЮБОЕ изменение
    состава (новая подделка, правка старого комментария под маркер),
    «новый ключ = новая эскалация» сохраняется; множество физически может
    только расти (правило репозитория запрещает удалять комментарии).
    Полный перечень id остаётся в строке отчёта build_report, туда ему и
    место; тело эскалации ограничено счётчиком и последним нарушителем."""
    ids = ",".join(str(i) for i in sorted(v["id"] for v in violations))
    return hashlib.sha1(ids.encode("utf-8")).hexdigest()[:16]


