def heartbeat_check(repo: str, now: datetime) -> list[str]:
    """«Кто следит за следящим»: вызывается КАЖДЫМ запуском планировщика до всей
    остальной работы. Опоздавший запуск — единственный, кто может закричать о
    пропавших пульсах, поэтому проверка первая.

    Выборка идёт по `orchestra_tick_runs` — серверный фильтр `?event=...` на
    оба легитимных события (`schedule`, `workflow_dispatch`), не клиентская
    фильтрация одной сырой страницы: `per_page=100` на КАЖДЫЙ запрос не
    тратится на `pull_request`-прогоны `contract`, так что труncация страницы
    настоящими тиками (найдено ревью PR #318) больше не молчит."""
    runs = orchestra_tick_runs(repo, per_page=100)
    last_ok = next((r for r in runs if r.get("conclusion") == "success"), None)
    if last_ok is None:
        # Пустой результат ПОСЛЕ серверного фильтра — не «выборка коротка»
        # (см. docstring выше), а «настоящих тиков не найдено вовсе» за 100
        # последних прогонов каждого легитимного события: сам по себе редкий
        # и тревожный случай (workflow мог быть отключён GitHub'ом после 60
        # дней простоя, docs/research/21), поэтому кричим, а не молчим ℹ️.
        text = (f"🚨 edge-harness: {HEARTBEAT_NO_TICKS_MARKER}\n"
                f"Успешных прогонов {ORCHESTRA_WORKFLOW} (schedule/workflow_dispatch) "
                "не найдено за последние 100 прогонов каждого события — пульс не "
                "подтверждён, возможен отключённый workflow (docs/research/21).")
        delivered = send_telegram(text)
        # posted/attempted — находка AI-ревью PR #318, третий раунд: строка
        # отчёта раньше безусловно утверждала «след в #120», даже если
        # post_issue_comment упал (RuntimeError уходил только в warning) —
        # именно в сценарии «тиков нет» канал задачи может быть сломан по
        # той же причине, что и пульс, поэтому отчёт не может тут врать.
        attempted = False
        posted = False
        try:
            # Двухмаркерный приём (episode_reopened, находка ревью PR #318, п.1):
            # без этого первое же «тиков нет» глушило бы канал комментария
            # навсегда — issue_marker_times ищет подстроку по ВСЕЙ истории #120.
            open_times = issue_marker_times(repo, WATCHDOG_ISSUE, HEARTBEAT_NO_TICKS_MARKER)
            close_times = issue_marker_times(repo, WATCHDOG_ISSUE, HEARTBEAT_TICKS_RESUMED_MARKER)
            if episode_reopened(open_times, close_times):
                attempted = True
                post_issue_comment(repo, WATCHDOG_ISSUE, text)
                posted = True
        except RuntimeError as error:
            print(f"::warning::след в #{WATCHDOG_ISSUE} не оставлен: {error}", file=sys.stderr)
        trace = "оставлен" if posted else ("НЕ оставлен" if attempted else "не требовался — эпизод не новый")
        return [f"🚨 успешных прогонов {ORCHESTRA_WORKFLOW} (schedule/workflow_dispatch) "
                f"не найдено (Telegram: {'доставлен' if delivered else 'НЕ доставлен'}; "
                f"след в #{WATCHDOG_ISSUE}: {trace})"]
    try:
        # Эпизод HEARTBEAT_NO_TICKS закрывается явно, как только тики снова
        # нашлись: без этого закрывающего маркера episode_reopened никогда не
        # увидит момент восстановления и следующий «тиков нет» останется
        # заглушен первым же старым маркером (тот же класс, что фикс выше).
        open_times = issue_marker_times(repo, WATCHDOG_ISSUE, HEARTBEAT_NO_TICKS_MARKER)
        if open_times:
            close_times = issue_marker_times(repo, WATCHDOG_ISSUE, HEARTBEAT_TICKS_RESUMED_MARKER)
            if not close_times or max(open_times) > max(close_times):
                post_issue_comment(
                    repo, WATCHDOG_ISSUE,
                    f"✅ edge-harness: {HEARTBEAT_TICKS_RESUMED_MARKER}\n"
                    f"Успешный прогон {ORCHESTRA_WORKFLOW} снова найден — эпизод "
                    "«тиков нет» закрыт.",
                )
    except RuntimeError as error:
        print(f"::warning::закрытие эпизода в #{WATCHDOG_ISSUE} не оставлено: {error}", file=sys.stderr)
    age = heartbeat_age_minutes(last_ok["created_at"], now)
    if decide_heartbeat(last_ok["created_at"], now) == "ok":
        return [f"💗 пульс orchestra в норме: последний успех {int(age)} мин назад "
                f"(порог {HEARTBEAT_MAX_AGE_MINUTES})"]
    text = heartbeat_alert_text(age, last_ok)
    delivered = send_telegram(text)
    # posted/attempted — тот же класс, что и в ветке HEARTBEAT_NO_TICKS выше
    # (находка AI-ревью PR #318, третий раунд): безусловное «след в #120» в
    # тексте отчёта было неверно, если post_issue_comment упал.
    attempted = False
    posted = False
    try:
        # Telegram — на каждый опоздавший запуск; след в задаче — один на эпизод:
        # новый комментарий только если прежний маркер старше последнего успеха
        # (пульсы успели восстановиться и снова пропали).
        markers = issue_marker_times(repo, WATCHDOG_ISSUE, HEARTBEAT_MARKER)
        if pause_notification_pending(markers, parse_time(last_ok["created_at"])):
            attempted = True
            post_issue_comment(repo, WATCHDOG_ISSUE, text)
            posted = True
    except RuntimeError as error:
        print(f"::warning::след в #{WATCHDOG_ISSUE} не оставлен: {error}", file=sys.stderr)
    trace = "оставлен" if posted else ("НЕ оставлен" if attempted else "не требовался — эпизод не новый")
    return [f"🚨 пульс orchestra пропадал: последний успех {int(age)} мин назад "
            f"> {HEARTBEAT_MAX_AGE_MINUTES} (Telegram: "
            f"{'доставлен' if delivered else 'НЕ доставлен'}; след в #{WATCHDOG_ISSUE}: {trace})"]


def decide_independent_pulse(
    dispatch_runs: list[dict], now: datetime,
    stale_after_minutes: float = INDEPENDENT_PULSE_STALE_AFTER_MINUTES,
) -> tuple[str, datetime | None, bool]:
    """Чистое решение #689. dispatch_runs — прогоны orchestra.yml с
    event=workflow_dispatch (прод-форма, поле triggering_actor.login читается
    как есть от Actions API). Возвращает (состояние, anchor, exact):

    'not_applicable' — событийный канал (EVENT_ACTOR_LOGIN) сам не подтверждён
    живым в пределах stale_after_minutes — честная граница: если оркестратор
    вообще не диспатчился недавно, отличить «независимый канал умер» от
    «PR-активности просто нет» по этим данным нельзя, тревогу не заводим.

    'ok'/'stale' — применимо (событийный канал жив): среди dispatch_runs есть
    хотя бы один прогон НЕ от EVENT_ACTOR_LOGIN не старше порога — 'ok'. anchor
    в этом случае — момент последнего независимого тика, exact=True (возраст
    точный). Если независимых прогонов в выборке нет вовсе — 'stale', anchor —
    самый старый прогон ВЫБОРКИ (нижняя граница возраста: провал не моложе
    этого момента, но неизвестно насколько старше), exact=False — вызывающий
    обязан назвать эту границу приблизительной, а не гадать точным числом."""
    event_runs = [r for r in dispatch_runs
                  if (r.get("triggering_actor") or {}).get("login") == EVENT_ACTOR_LOGIN]
    if not event_runs:
        return "not_applicable", None, True
    newest_event_age = min(minutes_between(parse_time(r["created_at"]), now) for r in event_runs)
    if newest_event_age > stale_after_minutes:
        return "not_applicable", None, True
    independent_runs = [r for r in dispatch_runs
                        if (r.get("triggering_actor") or {}).get("login") != EVENT_ACTOR_LOGIN]
    if not independent_runs:
        oldest = min(parse_time(r["created_at"]) for r in dispatch_runs)
        return "stale", oldest, False
    newest_independent_at = max(parse_time(r["created_at"]) for r in independent_runs)
    age = minutes_between(newest_independent_at, now)
    return ("ok" if age <= stale_after_minutes else "stale"), newest_independent_at, True


def independent_pulse_alert_text(age_minutes: float, exact: bool) -> str:
    hours = age_minutes / 60
    clause = (f"независимый пульс не приходил {hours:.1f} ч" if exact else
              f"независимый пульс не приходил как минимум {hours:.1f} ч "
              "(в изученной выборке дисптачей нет ни одного независимого тика)")
    return (
        f"🚨 edge-harness: {DO_PULSE_MARKER}\n"
        f"{clause} — конвейер держится только на событийном канале "
        "(scripts/gh/wake_orchestra.sh) и встанет, как только прекратится "
        "активность PR: нет ревью → некому продиспатчить orchestra.yml. "
        "Вероятная причина — cf-worker/src/harness.ts::alarm(): обе попытки "
        "ctx.storage.setAlarm упали, и цепочка пульса встала до "
        "пересоздания DO (issue #689); проверь rows_written квоту DO и "
        "/api/status морды."
    )


def independent_pulse_check(repo: str, now: datetime) -> list[str]:
    """Сторож живости #689 — ОБРАТНЫЙ по направлению класс к событийному
    сторожу (#510/#519, если он уже слит в этом дереве): тот проверяет, что
    событийный будильник (wake_orchestra.sh) сработал, этот — что независимый
    DO-пульс (cf-worker alarm()) сработал, пока событийный маскирует его
    смерть тем же трюком, каким schedule маскировал смерть job'а `orchestra`
    2026-09-05 (см. docstring real_orchestra_ticks).

    Применимость проверяется первой, дёшево (один recent_runs, per_page=100 —
    тот же порядок цены, что уже платит heartbeat_check за оба легитимных
    события): холостая очередь (событийный канал сам не подтверждён свежим)
    не пишет ничего и не заводит эпизода — не мониторинг падений, граница
    та же, что у failure_watch/event_wake_check."""
    dispatch_runs = recent_runs(repo, ORCHESTRA_WORKFLOW, per_page=100, event="workflow_dispatch")
    state, anchor, exact = decide_independent_pulse(dispatch_runs, now)
    if state == "not_applicable":
        return []
    age = minutes_between(anchor, now)

    if state == "ok":
        # Эпизод закрывается явно, как только независимый тик снова нашёлся —
        # тот же приём, что у HEARTBEAT_NO_TICKS/HEARTBEAT_TICKS_RESUMED выше.
        try:
            open_times = issue_marker_times(repo, WATCHDOG_ISSUE, DO_PULSE_MARKER)
            if open_times:
                close_times = issue_marker_times(repo, WATCHDOG_ISSUE, DO_PULSE_RESUMED_MARKER)
                if not close_times or max(open_times) > max(close_times):
                    post_issue_comment(
                        repo, WATCHDOG_ISSUE,
                        f"✅ edge-harness: {DO_PULSE_RESUMED_MARKER}\n"
                        "Прогон orchestra.yml с event=workflow_dispatch не от "
                        f"{EVENT_ACTOR_LOGIN} снова найден — эпизод «независимый "
                        "DO-пульс не приходил» закрыт.",
                    )
        except RuntimeError as error:
            print(f"::warning::закрытие эпизода DO-пульса в #{WATCHDOG_ISSUE} не оставлено: {error}",
                  file=sys.stderr)
        return [f"💗 независимый DO-пульс оркестратора в норме "
                f"(последний тик {int(age)} мин назад)"]

    try:
        open_times = issue_marker_times(repo, WATCHDOG_ISSUE, DO_PULSE_MARKER)
        close_times = issue_marker_times(repo, WATCHDOG_ISSUE, DO_PULSE_RESUMED_MARKER)
    except RuntimeError as error:
        return [f"⚠️ не смог сверить маркеры независимого DO-пульса #{WATCHDOG_ISSUE}: {error}"]
    if not episode_reopened(open_times, close_times):
        return [f"🚨 независимый DO-пульс не приходил ({int(age)} мин назад, эпизод уже оповещён)"]
    text = independent_pulse_alert_text(age, exact)
    result = escalate(repo, WATCHDOG_ISSUE, text)
    return [f"🚨 независимый DO-пульс не приходил {age / 60:.1f} ч ({result})"]


def conveyor_gate(repo: str, now: datetime) -> tuple[list[str], list[str], bool]:
    """Предохранитель: перед dispatch воркера. Возвращает (наблюдения,
    действия, разрешён_ли_диспетч) — разведено по #456: «диспатч разрешён» и
    «пауза уже объявлена» ничего не меняют на сервере и раньше делали
    conveyor_lines непустым буквально на КАЖДОМ прогоне (closed — обычное
    состояние здорового конвейера), из-за чего main() красноречиво врал
    «### Действия» там, где планировщик ничего не сделал. Действие — только
    там, где эта функция реально пишет (post_issue_comment/send_telegram):
    первая тревога серии (state=="first") и пробный диспатч (state=="probe").
    Три состояния (#205):

    closed — failures < порога, диспатч обычный, тихо;
    probe  — серия красная, выдержка с последнего маркера серии истекла —
             РОВНО ОДИН пробный диспатч в этом пульсе, маркер пробы ставится
             сразу (следующий пульс уже видит его и не пробует повторно, даже
             если этот прогон worker.yml ещё не успеет завершиться);
    open   — серия красная, выдержка не истекла — диспатч заблокирован, тихо
             (маркер уже стоит, второй раз не оповещаем).

    Сброс серии без пробы (#220): success-маркер RESUME_MARKER в #120 (его
    ставит scheduler.after_merge для мержа, чинившего причину) работает как
    виртуальный success — series_anchor берёт его вместо последнего зелёного
    прогона, и красные прогоны/маркеры старше якоря в решении не участвуют.

    Носитель состояния — комментарии-маркеры в #120 (тот же приём, что уже
    даёт issue_marker_times для пульса и что #196 использует для счётчика
    попыток ai-review): переживают перезапуск оркестратора, читаются заново
    каждым прогоном планировщика.

    count_consecutive_failures останавливается на первом незавершённом прогоне
    (conclusion=None) и возвращает 0 — это верно для «серии ещё не было», но
    ломается, если 0 означает «идёт проба текущей красной серии»: диспатч
    воркера на предыдущем пульсе ещё выполняется. Поэтому маркеры активной
    серии читаются ДО решения по failures — если маркер есть, failures=0 не
    может означать «closed», решение отдаётся decide_gate_state.

    Якорь серии — по completion-времени (`updated_at`), не по постановке в
    очередь (`created_at`), см. докстринг series_anchor/runs_after (#899):
    иначе успех, случившийся ПОСЛЕ того, как посреди него был поставлен
    маркер паузы/пробы, не может этот маркер снять — предохранитель стоит,
    пока не истечёт backoff, хотя причина уже давно чинилась.

    Ещё идущий прогон (conclusion=None) на голове списка при активной серии —
    отдельный класс (#899, п.2), не по этой же причине: судить, что делать
    ДАЛЬШЕ (новая проба, новый маркер), по прогону, чей исход ещё не известен,
    нельзя — сначала он должен завершиться."""
    runs = recent_runs(repo, WORKER_WORKFLOW, per_page=10)
    failures = count_consecutive_failures([r.get("conclusion") for r in runs])

    last_ok = next((r for r in runs if r.get("conclusion") == "success"), None)
    last_ok_at = parse_time(last_ok["updated_at"]) if last_ok else None
    try:
        all_markers = issue_markers_any(repo, WATCHDOG_ISSUE, (PAUSE_MARKER, RESUME_MARKER))
    except RuntimeError as error:
        if decide_dispatch(failures):
            return ([f"🟢 серия красных worker.yml: {failures} "
                     f"(порог {WORKER_FAILURE_PAUSE_AFTER}) — диспатч разрешён"], [],
                    True)
        # не смогли прочитать маркеры — не гадаем о выдержке, диспатч не даём
        # (fail loud: серия красная, значит по умолчанию заперто). Ничего не
        # писали на сервер — тоже наблюдение, не действие.
        print(f"::warning::маркеры #{WATCHDOG_ISSUE} не прочитаны: {error}", file=sys.stderr)
        return ([f"🚨 конвейер на паузе: {failures} красных прогонов {WORKER_WORKFLOW} "
                 f"подряд — диспатч остановлен (маркеры #{WATCHDOG_ISSUE} недоступны)"], [],
                False)
    # #220: success-маркер возобновления — виртуальный success серии. Якорь —
    # что новее, последний success или сброс мержем; красные прогоны и маркеры
    # серий старше якоря объяснены и в решении не участвуют — иначе сброс
    # мержем не снял бы ни счётчик, ни выдержку/номер попытки прошлой серии.
    resume_at = max((t for t, body in all_markers if RESUME_MARKER in body), default=None)
    anchor = series_anchor(last_ok_at, resume_at)
    failures = count_consecutive_failures(
        [r.get("conclusion") for r in runs_after(runs, anchor)])
    # Маркеры прошлой серии (старше якоря: success или сброс мержем) не в счёт —
    # иначе новая серия унаследует чужой номер попытки и выдержку с первого же
    # пульса. Маркеры возобновления выпадают сами: resume_at — наибольший из
    # них, якорь не бывает его старше, поэтому «строже якоря» не бывает.
    markers = [(t, body) for t, body in all_markers if anchor is None or t > anchor]
    if not markers and decide_dispatch(failures):
        allowed_line = (f"🟢 серия красных worker.yml: {failures} "
                        f"(порог {WORKER_FAILURE_PAUSE_AFTER}) — диспатч разрешён")
        if resume_at is not None and (last_ok_at is None or resume_at > last_ok_at):
            # сброс именно мержем, а не зелёным прогоном — назови причину
            allowed_line += " (серия сброшена мержем, см. #120)"
        return ([allowed_line], [], True)
    marker_times = [t for t, _ in markers]
    last_marker_at = max(marker_times) if marker_times else None
    probe_attempts = probe_marker_attempts(markers)

    # #899, п.2: голова списка ещё выполняется (conclusion=None) при активной
    # серии — исход неизвестен, новую пробу/маркер заводить рано. Без этой
    # проверки decide_gate_state видит только «выдержка истекла» и штампует
    # ВТОРУЮ пробу поверх ещё бегущей первой (второй одновременный
    # workflow_dispatch воркера), а last_failure_error(runs[0]) на ещё не
    # завершённом прогоне возвращает «упавшие job'ы не найдены (conclusion
    # прогона: None)» — эта бессмыслица уходит в тело НОВОГО маркера, как
    # будто это и есть причина паузы (живая цитата — маркер «проба 4» в #120,
    # 2026-09-10T17:06:17Z, посреди прогона 34498185823). Ничего не пишем —
    # это наблюдение, а не действие: маркер серии уже стоит, ждём исход.
    if runs and runs[0].get("conclusion") is None and markers:
        return ([f"⏳ конвейер на паузе: прогон "
                 f"{runs[0].get('html_url', 'без ссылки')} ещё выполняется — исход "
                 f"неизвестен, новую пробу не начинаем, диспатч остановлен "
                 f"(маркер серии уже стоит, см. #{WATCHDOG_ISSUE})"], [],
                False)

    # Маркер активной серии уже доказывает, что порог был достигнут раньше —
    # даже если сейчас failures=0 из-за незавершённой пробы (conclusion=None
    # останавливает count_consecutive_failures на 0, но это не значит «серия
    # закрылась»). Не даём decide_gate_state спутать это с closed.
    effective_failures = max(failures, WORKER_FAILURE_PAUSE_AFTER) if markers else failures
    state = decide_gate_state(effective_failures, probe_attempts, last_marker_at, now)

    if state == "open":
        # effective_failures, не failures (#899, п.3): failures — пересчёт
        # ПОСЛЕ якоря, он может быть 0, если маркер серии всё ещё в счёте, а
        # ни одного нового прогона после якоря не было — печатать в этом
        # случае «0 красных подряд — диспатч остановлен» самоопровергающе
        # (живая цитата инцидента). effective_failures — то число, которым
        # реально принято решение, текст обязан называть именно его.
        #
        # Уже оповещено раньше этим же прогоном серии — второй раз в #120 не
        # пишем В ЭТОМ ЖЕ забеге алгоритма (probe/first уже случились); но
        # длящаяся пауза сама по себе обязана быть видна без спама на каждый
        # 15-минутный пульс (#899, п.4) — до этой правки backoff-потолок в
        # 240 минут мог держать эпизод БЕЗ единого следа в #120 (живой
        # случай: ни одного нового комментария с 17:06 по 20:54). Throttle —
        # отдельный маркер PAUSE_REMINDER_MARKER, не участвующий в подсчёте
        # backoff (см. его докстринг), интервал PAUSE_REMINDER_INTERVAL_MINUTES.
        backoff = probe_backoff_minutes(probe_attempts + 1)
        remaining = max(0.0, backoff - minutes_between(last_marker_at, now))
        line = (f"🚨 конвейер на паузе: {effective_failures} красных прогонов "
                f"{WORKER_WORKFLOW} подряд (порог {WORKER_FAILURE_PAUSE_AFTER}) — "
                f"диспатч остановлен, следующая проба не раньше чем через "
                f"{int(remaining)} мин (маркер серии #{WATCHDOG_ISSUE} уже стоит)")
        try:
            reminder_times = issue_marker_times(repo, WATCHDOG_ISSUE, PAUSE_REMINDER_MARKER)
        except RuntimeError as error:
            print(f"::warning::напоминания #{WATCHDOG_ISSUE} не прочитаны: {error}", file=sys.stderr)
            reminder_times = []
        last_reminder_at = max(reminder_times, default=None)
        last_signal_times = [t for t in (last_marker_at, last_reminder_at) if t is not None]
        last_signal_at = max(last_signal_times) if last_signal_times else None
        if pause_reminder_due(last_signal_at, now):
            text = pause_reminder_text(effective_failures, remaining, runs[0] if runs else None)
            try:
                post_issue_comment(repo, WATCHDOG_ISSUE, text)
            except RuntimeError as err:
                print(f"::warning::напоминание в #{WATCHDOG_ISSUE} не доставлено: {err}", file=sys.stderr)
            delivered = send_telegram(text)
            return ([line], [f"⏳ напоминание о длящейся паузе: следующая проба через "
                     f"{int(remaining)} мин (Telegram: "
                     f"{'доставлен' if delivered else 'НЕ доставлен'}; след в #{WATCHDOG_ISSUE})"],
                    False)
        return ([line], [], False)

    error = last_failure_error(repo, runs[0]) if runs else "прогонов не найдено"
    if state == "probe":
        attempt = probe_attempts + 1
        backoff = probe_backoff_minutes(attempt)
        text = probe_alert_text(attempt, backoff, runs[0] if runs else None, error)
        try:
            post_issue_comment(repo, WATCHDOG_ISSUE, text)
        except RuntimeError as err:
            print(f"::warning::сигнал в #{WATCHDOG_ISSUE} не доставлен: {err}", file=sys.stderr)
        delivered = send_telegram(text)
        return ([], [f"🔎 пробный диспатч после паузы {int(backoff)} мин (попытка {attempt}) — "
                 f"{failures} красных {WORKER_WORKFLOW} подряд (Telegram: "
                 f"{'доставлен' if delivered else 'НЕ доставлен'}; сигнал в #{WATCHDOG_ISSUE})"],
                True)

    # state == "first": серия только что стала красной, маркера ещё нет —
    # ставим PAUSE_MARKER, диспатч не даём (выдержка отсчитается от этого
    # маркера, проба — не раньше следующего пульса).
    text = pause_alert_text(failures, runs[0] if runs else None, error)
    try:
        post_issue_comment(repo, WATCHDOG_ISSUE, text)
    except RuntimeError as err:
        print(f"::warning::сигнал в #{WATCHDOG_ISSUE} не доставлен: {err}", file=sys.stderr)
    delivered = send_telegram(text)
    return ([], [f"🚨 конвейер на паузе: {failures} красных прогонов {WORKER_WORKFLOW} "
             f"подряд — диспатч остановлен (Telegram: "
             f"{'доставлен' if delivered else 'НЕ доставлен'}; сигнал в #{WATCHDOG_ISSUE})"],
            False)


FAILURE_FINGERPRINT_MARKER = "<!-- failure-fingerprint: "


def open_ci_failure_issues(repo: str) -> list[dict]:
    """Открытые issues с меткой FAILURE_WATCH_LABEL — сырой список, единый
    источник и для точного дедупа по fingerprint (ci_failure_fingerprints),
    и для дедупа по похожести заголовка (#610, см. failure_watch): один обход
    Issues на оба вопроса, не два отдельных запроса подряд.

    Листает страницы через review_labels.list_pages (класс #308, тот же
    приём, что all_issue_comments выше — одно место правды на обход и на
    fail loud при неожиданной форме ответа, дефект A #120): список НЕ
    ограничен по природе — долгоживущие незакрытые дефекты CI со временем
    накопятся так же, как обычный пул задач, а сырая первая страница молча
    потеряла бы хвост — та же ошибка дедупа, что и без него, просто
    отложенная во времени. Значение метки в query кодируется
    review_labels.label_query_value (класс инцидента #938)."""
    return review_labels.list_pages(
        f"repos/{repo}/issues?state=open&labels="
        f"{review_labels.label_query_value(FAILURE_WATCH_LABEL)}&per_page=100", gh)


def ci_failure_fingerprints(issues: list[dict]) -> set[str]:
    """Отпечатки, уже заведённые задачами из open_ci_failure_issues — дедуп
    «дефект этого КЛАССА уже в пуле» (точное совпадение нормализованного
    факта). Чистая функция над уже прочитанным списком — второй обход Issues
    здесь не заводится (см. open_ci_failure_issues)."""
    found: set[str] = set()
    for issue in issues:
        body = issue.get("body") or ""
        idx = body.find(FAILURE_FINGERPRINT_MARKER)
        if idx == -1:
            continue
        rest = body[idx + len(FAILURE_FINGERPRINT_MARKER):]
        found.add(rest.split(" ", 1)[0].split("-->", 1)[0].strip())
    return found


def ci_failure_created_since(repo: str, since: datetime) -> int:
    """Сколько задач FAILURE_WATCH_LABEL заведено не раньше `since` — суточный
    потолок считается по факту СОЗДАНИЯ, не по текущей открытости (закрытая
    сегодня задача всё равно сожгла квоту дня) — тот же приём, что
    stall_detector.auto_tasks_created_since (см. FAILURE_WATCH_DAILY_CAP: свой
    счётчик, своя метка, не общий с auto-detected).

    `state=all`, не `state=open` (в отличие от open_ci_failure_fingerprints
    выше — тому дедупу закрытые не нужны, счётчику потолка — нужны). Листает
    страницы через review_labels.list_pages (класс #308, дефект A #120):
    сырая первая страница молча занижала бы потолок после сотни ci-failure
    задач за всё время; не-list ответ раньше давал то же самое молча —
    теперь падает громко, вместо заниженного потолка. Значение метки в
    query кодируется review_labels.label_query_value (класс #938)."""
    issues = review_labels.list_pages(
        f"repos/{repo}/issues?state=all&labels="
        f"{review_labels.label_query_value(FAILURE_WATCH_LABEL)}&per_page=100", gh)
    return sum(
        1 for issue in issues
        if "pull_request" not in issue and parse_time(issue["created_at"]) >= since
    )


def failure_watch_cap_exhausted(created_today: int, cap: int = FAILURE_WATCH_DAILY_CAP) -> bool:
    """True — суточный потолок автозаведения ci-failure задач исчерпан, новый
    класс задачей не заводится (см. FAILURE_WATCH_DAILY_CAP)."""
    return created_today >= cap


def failure_watch_cap_alert_text(cap_marker: str, created_today: int, skipped_today: list[str]) -> str:
    """Текст видимого сигнала об исчерпании потолка (#120 + Telegram, один раз
    на переход — см. FAILURE_WATCH_CAP_MARKER). `cap_marker` уже несёт дату
    (issue_marker_times дедуплицирует по ТОЧНО этому маркеру). Перечисляет
    отсечённые классы ЭТОГО пульса — не значит, что дальнейшие в этот же день
    классы теряются: каждый новый класс получает свой тихий след-комментарий
    (FAILURE_WATCH_CAP_SKIP_MARKER_PREFIX, дедуп по (день, отпечаток)),
    смотреть там."""
    listed = "\n".join(f"- `{fp}`" for fp in skipped_today) or "- (список появится по мере отсечения новых классов)"
    return (
        f"🚨 edge-harness: {cap_marker}\n"
        f"Суточный потолок автозаведения {FAILURE_WATCH_LABEL} задач "
        f"({created_today}/{FAILURE_WATCH_DAILY_CAP}) исчерпан — "
        "новые дефекты CI НЕ заводят задачу, нужен человек.\n\n"
        f"Отсечённые классы этого пульса:\n{listed}\n\n"
        "Это НЕ отказ пульса: failure_watch жив и продолжает наблюдать — прогон "
        "нарочно НЕ покрашен красным (инвариант «наблюдатель провалов не "
        "реагирует на свою инфраструктуру мониторинга»). Дальнейшие отсечённые "
        f"классы этого дня — тихим следом в #{WATCHDOG_ISSUE} "
        f"(маркер «{FAILURE_WATCH_CAP_SKIP_MARKER_PREFIX}»), без повторной тревоги.\n\n"
        "Что дальше: посмотреть открытые задачи с меткой "
        f"{FAILURE_WATCH_LABEL} и след в #{WATCHDOG_ISSUE}, решить руками по "
        "каждому отсечённому классу — приоритизировать, завести задачу вручную "
        "(scripts/gh/issue-create) или поднять FAILURE_WATCH_DAILY_CAP, если "
        "объём временный."
    )


def failure_watch_task_body(workflow: str, job_name: str, fact: str, run_url: str, fingerprint: str, steps: str) -> str:
    """Тело авто-заведённой задачи — тот же формат, что шаблон «📋 Задача в
    пул» (Цель/Критерий/Площадь), плюс отпечаток класса HTML-комментарием:
    ci_failure_fingerprints ищет именно эту строку, не парсит прозу.
    Упавшие шаги — рядом с фактом (критерий #477 называет «шаг + последняя
    ##[error]-строка»): их имена уже прочитаны из job'а, второй запрос не
    нужен (чеклист ревью PR #488)."""
    return (
        f"## Цель\n"
        f"`{workflow}` (job «{job_name}») перестаёт падать этой причиной.\n\n"
        f"## Критерий готовности\n"
        f"Следующий прогон `{workflow}` на этом коде зелёный, либо причина "
        "документированно устранена в другом месте (тогда — закрыть со ссылкой).\n\n"
        f"## Площадь\n"
        "area:orchestra\n\n"
        f"## Контекст и ссылки\n"
        f"Живой прогон: {run_url}\n"
        f"Упавшие шаги job'а «{job_name}»: {steps}\n"
        f"Факт: {fact}\n\n"
        f"<!-- failure-fingerprint: {fingerprint} -->\n"
    )


def failure_watch(repo: str, now: datetime) -> tuple[list[str], list[str]]:
    """Провалы ключевых workflow (#477): дешёвый опрос `status=completed`
    с клиентским фильтром по выводу (FAILURE_WATCH_RUN_CONCLUSIONS:
    failure + timed_out, без cancelled — см. комментарий у константы; одна
    страница per_page=100 на workflow — единый размер FAILURE_WATCH_PER_PAGE,
    без выгрузки логов всех прогонов
    подряд — квота API дорога, см. rate_guard.py) по каждому
    WATCHED_WORKFLOWS. Для самого свежего провала — по каждому упавшему job'у
    (до FAILURE_WATCH_MAX_JOBS_PER_RUN): последняя содержательная строка
    `##[error]` из лога (факт, не гипотеза), классификация
    (classify_failure_cause) и дедуп по failure_fingerprint (класс причины,
    НЕ run id — один сигнал на класс):

    'stale_base' — газ уже назван в другом месте (#474, task-branch/pre-commit
                   сами просят git rebase) — только наблюдение, без задачи и
                   без следа в #120 (не дублировать уже объявленный газ);
    'infra'      — известная сигнатура лимита/сети — лечится ожиданием: один
                   тихий след в #120 на класс (issue_marker_times — тот же
                   приём, что у остальных маркеров серий), Telegram не шлём —
                   это не тревога, требующая действия человека;
    'defect'     — наш дефект: задача в пул (label task + FAILURE_WATCH_LABEL)
                   с конкретным фактом, если такого класса ещё нет среди
                   открытых issues с меткой FAILURE_WATCH_LABEL и если суточный
                   потолок FAILURE_WATCH_DAILY_CAP не исчерпан (см. константу и
                   ci_failure_created_since) — исчерпание НЕ красит прогон и не
                   теряет отсечённый класс молча: тихий след-комментарий на
                   класс (дедуп по (день, отпечаток)) плюс видимая эскалация
                   #120+Telegram раз в сутки на переход (FAILURE_WATCH_CAP_MARKER).

    Прогоны `event=pull_request` не разбираются (находка ревью PR #488,
    раунд 2): красный прогон PR-события — это красный обязательный чек на PR,
    его устойчивую причину уже заводит автодетектор простоя (stall_detector,
    #201, отпечаток `check:red:<имя>`); вторая задача с меткой ci-failure на
    тот же дефект — ровно тот спам, который запрещает критерий #477. Вариант
    «перед заведением сверяться и с открытыми auto-detected» не выбран:
    отпечатки двух детекторов несопоставимы (хэш против slug), а после
    исключения PR-событий классы двух путей не пересекаются.

    Строка ошибки не прочиталась — задача НЕ заводится (находка ревью PR #488,
    чеклист): фолбэк-факт «шаги: …» грубее отпечатка с настоящей строкой,
    задача по нему мигает во вторую, когда лог на следующем пульсе
    прочитается. Критерий #477 требует точную причину — остаётся громкое
    наблюдение (⚠️); устойчивый случай подберёт автодетектор #201 (класс
    warn:), факт не теряется — ссылка на прогон в строке наблюдения.

    Окно свежести измеряется от updated_at (момент провала), не от created_at
    (момент постановки в очередь) — иначе провалы долгих прогонов (worker.yml
    пашет десятки минут по замыслу) лежат вне окна на каждом пульсе. Реран
    старого прогона обновляет updated_at — прогон снова «свежий», ПОКА задача
    класса открыта (defect) или маркер в #120 стоит (infra) повторного
    сигнала/задачи это не даёт: дедуп смотрит на них, не на свежесть. После
    закрытия задачи реран в окне заведёт новую задачу на ту же причину — это
    не бесконечный цикл, а переоткрытие эпизода с ограничителем-окном:
    причина снова красит свежий прогон, значит снова требует разбора."""
    observations: list[str] = []
    actions: list[str] = []
    # Ленивая инициализация — только если дошли до дефекта: оба читаются из
    # одного обхода Issues (open_ci_failure_issues), второго запроса нет.
    ci_issues: list[dict] | None = None
    ci_fingerprints: set[str] | None = None
    ci_created_today: int | None = None  # тоже лениво — суточный потолок (FAILURE_WATCH_DAILY_CAP)
    cap_skipped_this_pulse: list[str] = []  # классы, отсечённые потолком в ЭТОМ пульсе (см. цикл ниже)

    for workflow in WATCHED_WORKFLOWS:
        try:
            # status=completed (не status=failure): серверный фильтр failure
            # не возвращает timed_out — провал по собственному капу остался бы
            # неразобранным (находка ревью PR #488, раунд 3); вывод
            # фильтруется клиентским списком FAILURE_WATCH_RUN_CONCLUSIONS.
            # Размер страницы — единый FAILURE_WATCH_PER_PAGE (см. константу).
            payload = gh(
                f"repos/{repo}/actions/workflows/{workflow}"
                f"/runs?status=completed&per_page={FAILURE_WATCH_PER_PAGE}"
            ) or {}
        except RuntimeError as error:
            observations.append(f"⚠️ failure-watch {workflow}: список провалов не прочитан ({error})")
            continue
        runs = payload.get("workflow_runs", [])
        # Класс «красный прогон PR-события» уже ведёт check:red-путь #201 (см.
        # докстринг) — вычитается ДО окна свежести. Фильтр клиентский, не
        # серверный `event=`: у API нет «не равно», а перебор легитимных
        # событий — по запросу на каждое событие каждого workflow против одной
        # страницы здесь. Страница — запас, чтобы клиентские фильтры
        # (PR-прогоны, отменённые) не вытеснили свежий провал основного
        # события за страницу; потеря хвоста за страницей стоит не дороже
        # окна ниже — вне окна разбор и так не идёт.
        runs = [r for r in runs if r.get("event") != "pull_request"]
        runs = [r for r in runs if r.get("conclusion") in FAILURE_WATCH_RUN_CONCLUSIONS]
        # Окно свежести (находка ревью PR #488): провал старше окна уже не
        # актуален — задачу на него заводить поздно и незачем, `now` не
        # декорация. Без фильтра `runs[0]` навсегда остаётся тем же старым
        # красным прогоном после закрытия задачи по нему. Якорь — updated_at
        # (момент провала), не created_at (момент постановки в очередь):
        # см. комментарий у FAILURE_WATCH_WINDOW_MINUTES.
        fresh_cutoff = now - timedelta(minutes=FAILURE_WATCH_WINDOW_MINUTES)
        runs = [r for r in runs if parse_time(r["updated_at"]) >= fresh_cutoff]
        if not runs:
            continue
        run_item = runs[0]  # самый свежий провал этого workflow в пределах окна
        # Сбой запроса job'ов — отдельное наблюдение с причиной, не склейка с
        # «упавший job не найден»: свод источников (failing_jobs) отдаёт
        # RuntimeError, «сбой» и «пусто» — разные факты (чеклист ревью PR #488).
        try:
            bad_jobs = failing_jobs(repo, run_item, FAILURE_WATCH_RUN_CONCLUSIONS)
        except RuntimeError as error:
            observations.append(
                f"⚠️ failure-watch {workflow}: job'ы прогона "
                f"{run_item.get('html_url')} не прочитаны ({error})")
            continue
        if not bad_jobs:
            observations.append(
                f"⚠️ failure-watch {workflow}: прогон {run_item.get('html_url')} красный, "
                f"упавших job'ов с выводом {('+'.join(FAILURE_WATCH_RUN_CONCLUSIONS))} не найдено")
            continue
        run_url = run_item.get("html_url", "")
        # Каждый упавший job — отдельный кандидат класса: разные job'ы одного
        # прогона падают по разным причинам, и раньше разбирался только
        # bad_jobs[0] (находка ревью PR #488, чеклист). Лог job'а — дорогой
        # запрос, поэтому потолок FAILURE_WATCH_MAX_JOBS_PER_RUN; хвост НЕ
        # прячется — назван поимённо в наблюдении после цикла.
        for job in bad_jobs[:FAILURE_WATCH_MAX_JOBS_PER_RUN]:
            error_line = last_error_log_line(repo, job["id"])
            job_name = job.get("name", "?")
            step_names = ", ".join(
                step["name"] for step in job.get("steps", [])
                if step.get("conclusion") in FAILURE_CONCLUSIONS
            ) or "нет (упал до шагов)"
            if error_line is None:
                observations.append(
                    f"⚠️ failure-watch {workflow} (job «{job_name}»): прогон {run_url} красный, "
                    f"строка ##[error] недоступна (шаги: {step_names}) — задачу не "
                    "заводим без факта, устойчивый случай возьмёт автодетектор (#201, warn:)")
                continue
            fact = error_line
            cause = classify_failure_cause(f"{error_line} {step_names}")
            fingerprint = failure_fingerprint(workflow, job_name, fact)

            if cause == "stale_base":
                observations.append(
                    f"⏭️ failure-watch {workflow} (job «{job_name}»): устаревшая база "
                    f"(класс {fingerprint}) — газ уже назван в #474/task-branch "
                    "(git rebase), задачу не дублируем")
                continue

            if cause == "infra":
                marker = f"{FAILURE_WATCH_INFRA_MARKER} {fingerprint}]"
                try:
                    already = bool(issue_marker_times(repo, WATCHDOG_ISSUE, marker))
                except RuntimeError as error:
                    observations.append(
                        f"⚠️ failure-watch {workflow} (job «{job_name}»): маркеры "
                        f"#{WATCHDOG_ISSUE} не прочитаны ({error})")
                    continue
                if already:
                    observations.append(
                        f"🕓 failure-watch {workflow} (job «{job_name}»): инфраструктурная "
                        f"причина, класс {fingerprint} (уже сигналили) — молча ждём")
                    continue
                text = (
                    f"🕓 edge-harness: {marker}\n"
                    f"{workflow} (job «{job_name}») падает по инфраструктурной причине, "
                    "не наш дефект — лечится ожиданием, задача в пул не заводится.\n"
                    f"Факт: {fact}\n"
                    f"{run_url}"
                )
                # posted — находка ревью PR #488 (раунд 2; тот же класс, что
                # heartbeat_check после PR #318): упавший пост уходит в
                # warning, и отчёт не вправе утверждать «след оставлен».
                posted = True
                try:
                    post_issue_comment(repo, WATCHDOG_ISSUE, text)
                except RuntimeError as error:
                    posted = False
                    print(f"::warning::след в #{WATCHDOG_ISSUE} не оставлен: {error}", file=sys.stderr)
                observations.append(
                    f"🕓 failure-watch {workflow} (job «{job_name}»): инфраструктурная "
                    f"причина, класс {fingerprint} — след в #{WATCHDOG_ISSUE} "
                    f"{'оставлен' if posted else 'НЕ оставлен'}, диспатч не трогаем")
                continue

            # cause == "defect": заводим задачу, если класса ещё нет в пуле.
            if ci_issues is None:
                try:
                    ci_issues = open_ci_failure_issues(repo)
                except RuntimeError as error:
                    observations.append(
                        f"⚠️ failure-watch {workflow}: список задач {FAILURE_WATCH_LABEL} не прочитан ({error})")
                    continue
                ci_fingerprints = ci_failure_fingerprints(ci_issues)
            if fingerprint in ci_fingerprints:
                observations.append(
                    f"🔁 failure-watch {workflow} (job «{job_name}»): дефект класса "
                    f"{fingerprint} уже в пуле — не дублируем")
                continue

            title = f"CI: {workflow} падает — {job_name}"
            # Дедуп по ТОЧНОМУ заголовку (#610) — ДО потолка и ДО создания,
            # поверх дедупа по fingerprint выше: заголовок детерминирован
            # (workflow, job_name) — для одной и той же пары ВСЕГДА один и тот
            # же байт-в-байт текст, а fingerprint чувствителен к точному
            # тексту факта (см. last_error_log_line/POST_JOB_CLEANUP_MARKER —
            # расходящийся факт при одной и той же причине порождал разные
            # fingerprint при ОДИНАКОВОМ заголовке, живой случай
            # #578/#580/#589/#592/#598). Нарочно точное совпадение, не
            # Jaccard-схожесть duplicate_guard (см. scripts/gh/issue-create):
            # у duplicate_guard заголовки придумывает человек/агент, здесь —
            # фиксированный шаблон, где РАЗНЫЕ job_name обязаны оставаться
            # РАЗНЫМИ классами (например «job-0» и «job-1» после токенизации
            # по словам совпали бы Jaccard'ом в одно — regression test
            # test_failure_watch_parses_jobs_up_to_cap_and_names_the_rest —
            # точное сравнение строк этого не путает.
            # ДО потолка (не после): комментарий на уже существующую issue не
            # заводит новую задачу и не должен сжигать суточную квоту
            # FAILURE_WATCH_DAILY_CAP — иначе исчерпанный потолок молча
            # блокировал бы даже улику к уже открытому дефекту, хотя пул при
            # этом не растёт вовсе.
            existing_by_title = next(
                (issue for issue in ci_issues
                 if "pull_request" not in issue and issue.get("title") == title),
                None,
            )
            if existing_by_title:
                number = existing_by_title["number"]
                # Дедуп комментария по КЛАССУ (тот же приём, что
                # stall_detector._evidence_marker/issue_marker_times, находка
                # PR #248): свежий провал остаётся в окне FAILURE_WATCH_WINDOW_MINUTES
                # несколько пульсов подряд (пульс — раз в 15 мин, окно — 30) — без
                # этой проверки КАЖДЫЙ пульс писал бы БАЙТ-В-БАЙТ одинаковый
                # комментарий на #578 (находка ревью PR #612: три пульса одного
                # прогона на моках дали два дубля). ci_fingerprints выше не
                # спасает: он парсит только ТЕЛА issues (open_ci_failure_issues/
                # ci_failure_fingerprints), этот же класс комментарием, а не
                # телом — маркер нужно искать среди комментариев ИМЕННО этой
                # issue (issue_marker_times), не среди тел.
                marker = f"{FAILURE_FINGERPRINT_MARKER}{fingerprint} -->"
                try:
                    already_commented = bool(issue_marker_times(repo, number, marker))
                except RuntimeError as error:
                    observations.append(
                        f"⚠️ failure-watch {workflow} (job «{job_name}»): комментарии "
                        f"#{number} не прочитаны ({error})")
                    continue
                if already_commented:
                    observations.append(
                        f"🔁 failure-watch {workflow} (job «{job_name}»): issue с тем же заголовком "
                        f"и классом {fingerprint} уже прокомментирована (#{number}) — молчу")
                    continue
                # Текст не утверждает «новый прогон» (находка ревью PR #612: до
                # дедупа выше это было буквально ложью на повторном пульсе того
                # же прогона) — только факт, что у issue уже есть отпечаток
                # ДРУГОГО класса причины под тем же заголовком.
                comment = (
                    f"{marker}\n"
                    f"У issue с тем же заголовком уже записан другой отпечаток факта — "
                    f"новый класс {fingerprint}, комментарий вместо второй issue (#610):\n\n"
                    f"Факт: {fact}\n{run_url}"
                )
                try:
                    post_issue_comment(repo, number, comment)
                    posted = True
                except RuntimeError as error:
                    posted = False
                    print(f"::warning::след в #{number} не оставлен: {error}", file=sys.stderr)
                ci_fingerprints.add(fingerprint)
                observations.append(
                    f"🔁 failure-watch {workflow} (job «{job_name}»): issue с тем же заголовком "
                    f"уже открыта (#{number}) — "
                    f"{'улика оставлена' if posted else 'улика НЕ оставлена'}, новую issue не завожу")
                continue

            # Суточный потолок (FAILURE_WATCH_DAILY_CAP): класс новый, титул
            # тоже новый (иначе выше уже вышли комментарием), но квота дня
            # исчерпана — задача НЕ заводится. Отсечённый класс не теряется
            # молча: тихий след-комментарий в WATCHDOG_ISSUE (дедуп по (день,
            # отпечаток) — не на каждый пульс) плюс видимая эскалация раз в
            # сутки на переход (после цикла по workflow, ниже).
            if ci_created_today is None:
                try:
                    ci_created_today = ci_failure_created_since(repo, now - timedelta(hours=24))
                except RuntimeError as error:
                    observations.append(
                        f"⚠️ failure-watch {workflow}: счётчик суточного потолка "
                        f"{FAILURE_WATCH_LABEL} не прочитан ({error})")
                    continue
            if failure_watch_cap_exhausted(ci_created_today):
                observations.append(
                    f"🚨 failure-watch {workflow} (job «{job_name}»): суточный потолок "
                    f"{FAILURE_WATCH_LABEL} ({ci_created_today}/{FAILURE_WATCH_DAILY_CAP}) "
                    f"исчерпан — класс {fingerprint} НЕ заведён, нужен человек")
                cap_skipped_this_pulse.append(fingerprint)
                skip_marker = (f"{FAILURE_WATCH_CAP_SKIP_MARKER_PREFIX} "
                               f"{now.date().isoformat()} {fingerprint}]")
                try:
                    already_listed = bool(issue_marker_times(repo, WATCHDOG_ISSUE, skip_marker))
                except RuntimeError as error:
                    observations.append(
                        f"⚠️ failure-watch {workflow}: маркеры #{WATCHDOG_ISSUE} не прочитаны ({error})")
                    already_listed = True  # не гадаем повторно на этом же пульсе
                if not already_listed:
                    try:
                        post_issue_comment(
                            repo, WATCHDOG_ISSUE,
                            f"{skip_marker}\nfailure-watch: класс {fingerprint} ({workflow}, job "
                            f"«{job_name}») отсечён суточным потолком {FAILURE_WATCH_LABEL} "
                            f"({FAILURE_WATCH_DAILY_CAP}/сутки) — задача НЕ заведена:\n\n"
                            f"Факт: {fact}\n{run_url}",
                        )
                        actions.append(
                            f"📋 failure-watch {workflow} (job «{job_name}»): класс {fingerprint} "
                            f"отсечён потолком — след в #{WATCHDOG_ISSUE} оставлен")
                    except RuntimeError as error:
                        observations.append(
                            f"⚠️ failure-watch {workflow}: след об отсечённом классе {fingerprint} "
                            f"в #{WATCHDOG_ISSUE} не оставлен ({error})")
                continue

            body = failure_watch_task_body(
                workflow, job_name, fact, run_url, fingerprint, step_names)
            try:
                # Заведение issue пула — только через pool_issue.create_pool_issue
                # (одно место правды #526: labels без `task` — RuntimeError ДО
                # сетевого вызова; CI-гвардия «сырой POST repos/{repo}/issues
                # вне pool_issue.py» ловит обход — красный чек прогона
                # 34049072989 на этом PR).
                created = pool_issue.create_pool_issue(
                    gh, repo, title, body, ["task", FAILURE_WATCH_LABEL])
            except RuntimeError as error:
                observations.append(
                    f"⚠️ failure-watch {workflow} (job «{job_name}»): задача по дефекту не заведена ({error})")
                continue
            ci_fingerprints.add(fingerprint)
            ci_issues.append({
                "number": created.get("number"), "title": title,
                "html_url": created.get("html_url", ""), "body": body,
            })
            ci_created_today += 1  # эта задача уже сожгла квоту дня — следующий кандидат этого же пульса обязан её увидеть
            actions.append(
                f"🛠️ failure-watch {workflow}: заведена задача по дефекту "
                f"(job «{job_name}», шаги: {step_names}, класс {fingerprint}) — {fact}")
        hidden = bad_jobs[FAILURE_WATCH_MAX_JOBS_PER_RUN:]
        if hidden:
            observations.append(
                f"⚠️ failure-watch {workflow}: ещё {len(hidden)} упавших job'ов не разобраны "
                f"(потолок {FAILURE_WATCH_MAX_JOBS_PER_RUN} логов на прогон): "
                + ", ".join(f"«{j.get('name', '?')}»" for j in hidden))

    # Видимая эскалация исчерпания потолка (см. FAILURE_WATCH_CAP_MARKER) —
    # РОВНО один раз на переход в календарные сутки, не на каждый пульс, пока
    # потолок остаётся исчерпанным (дедуп маркером с датой). Список классов в
    # тексте — те, что отсечены ИМЕННО этим пульсом; классы, отсечённые позже
    # в этот же день, получают свой тихий след-комментарий (см. цикл выше),
    # не второй Telegram-сигнал.
    if cap_skipped_this_pulse:
        cap_marker = f"{FAILURE_WATCH_CAP_MARKER} {now.date().isoformat()}]"
        try:
            already_escalated_today = bool(issue_marker_times(repo, WATCHDOG_ISSUE, cap_marker))
        except RuntimeError as error:
            observations.append(
                f"⚠️ failure-watch: маркеры #{WATCHDOG_ISSUE} не прочитаны ({error}) — "
                "эскалация потолка не проверена")
            already_escalated_today = True  # не гадаем повторно на этом же пульсе
        if not already_escalated_today:
            text = failure_watch_cap_alert_text(cap_marker, ci_created_today, cap_skipped_this_pulse)
            result = escalate(repo, WATCHDOG_ISSUE, text)
            actions.append(
                f"🚨 failure-watch: эскалация потолка автозаведения {FAILURE_WATCH_LABEL} ({result})")

    return observations, actions
