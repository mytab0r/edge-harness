def open_blocked_issues(repo: str) -> list[dict]:
    """Открытые issues (не PR) с меткой `blocked`, обход страниц (класс #308)."""
    issues = review_labels.list_pages(
        f"repos/{repo}/issues?state=open&labels={review_labels.label_query_value(BLOCKED_LABEL)}"
        "&per_page=100",
        pulse_guard.gh,
    )
    return [issue for issue in issues if "pull_request" not in issue]


def fetch_comments_text(repo: str, number: int) -> list[str]:
    comments = review_labels.list_pages(
        f"repos/{repo}/issues/{number}/comments?per_page=100", pulse_guard.gh)
    return [comment.get("body") or "" for comment in comments]


def issue_state(repo: str, number: int) -> dict:
    """Полное состояние issue ИЛИ PR по общему issues-эндпоинту (PR доступен
    через него же) — не только `state`, но и `closed_at`/`closed_by` (полный
    single-issue ответ несёт оба поля, список-эндпоинт — нет), нужные для
    следа снятия метки (`removal_comment_text`, #1157). Пустой словарь —
    честный признак «ответа не было» (не путать с открытым issue)."""
    data = pulse_guard.gh(f"repos/{repo}/issues/{number}")
    return data if isinstance(data, dict) else {}


def target_status(repo: str, number: int) -> tuple[str, dict]:
    """Состояние потенциальной цели маркера — ТРИ состояния сверх обычных
    open/closed (issue #1211, требование третьего состояния): `"missing"` —
    номер не существует (`ai_review.is_not_found` — ТОЧНАЯ форма gh «HTTP
    404», не подстрока «404», см. импорт наверху), `"unknown"` — любой
    другой отказ (сеть/права/неожиданный ответ) — данные не получены, это
    НЕ «нарушений нет» (AGENTS.md «Fail loud, не silent-wrong»)."""
    try:
        data = issue_state(repo, number)
    except RuntimeError as error:
        if ai_review.is_not_found(error):
            return "missing", {}
        return "unknown", {"reason": str(error)}
    state = (data.get("state") or "").lower()
    if state not in ("open", "closed"):
        return "unknown", {"reason": f"неожиданный ответ gh для #{number}: {data!r}"}
    return state, data


def remove_label(repo: str, number: int) -> None:
    # label_query_value — то же место кодирования, что уже применяет
    # waiting_owner_guard.remove_label (issue #938: сырое двоеточие в пути
    # ломает gh api на плейсхолдерах `:owner`/`:repo`); у `blocked` спецсимволов
    # нет, но кодирование — не второе место правды, а то же самое, что и у
    # значения query выше (open_blocked_issues).
    pulse_guard.gh("-X", "DELETE",
                   f"repos/{repo}/issues/{number}/labels/"
                   f"{review_labels.label_query_value(BLOCKED_LABEL)}")


def stale_blocked_check(repo: str) -> list[str]:
    """Проводка: один живой прогон. Возвращает строки отчёта (пустой список —
    холостой ход, ни одной протухшей блокировки не найдено).

    С #1157: найденная протухшая блокировка (маркер + закрытая цель) больше
    не только эскалируется — метка снимается сама, след оставляется
    комментарием (`removal_comment_text`). Провал самого снятия (сеть/права)
    — единственный путь, оставшийся у эскалации `escalate()` в этом модуле.

    Доводка ревью PR #1216: состояния целей читает `target_status`, а не
    «сырой» `issue_state` — `missing`/`unknown` на одном номере (опечаточный
    N в маркере, разовый сбой gh) дают строку ❓ и пропуск этого номера, а
    не исключение на всю проводку; структурное поле «Чем блокируется»
    учитывается как причина метки, когда инлайн-маркера нет вовсе (см.
    докстринг `find_stale_blocked`, пункт 3 доводки)."""
    issues = open_blocked_issues(repo)
    for issue in issues:
        issue["comments_text"] = fetch_comments_text(repo, issue["number"])

    referenced: set[int] = set()
    inline_current: dict[int, int | None] = {}
    structural_by_number: dict[int, list[int]] = {}
    for issue in issues:
        number = issue["number"]
        texts = [issue.get("body") or ""] + issue["comments_text"]
        referenced.update(stale_marker_targets(number, texts))
        inline_current[number] = current_stale_marker_target(number, texts)
        # Причина метки из структурного поля — только когда инлайн-маркера
        # нет вовсе (последний инлайн-маркер старшинству не уступает, см.
        # докстринг `find_stale_blocked`).
        if inline_current[number] is None:
            kind, structural = structural_field_targets(issue.get("body") or "")
            if kind == "declared" and structural:
                structural_by_number[number] = structural
                referenced.update(structural)

    statuses = {number: target_status(repo, number) for number in referenced}
    closed_numbers = {number for number, (status, _) in statuses.items() if status == "closed"}

    lines: list[str] = []
    # Третье состояние на помеченной issue (доводка ревью, пункт 1): номер
    # не существует или не прочитан — метка НЕ снимается (факт протухания
    # не подтверждён, «Алерт не гадает»), шаг краснеет строкой ❓, а не
    # исключением на всю проводку. Газ — ручной и названный: правится
    # формулировка маркера/поля в задаче тем, кто её следующим прочтёт;
    # для unknown строка честно говорит, что причина невыясненной осталась.
    for issue in issues:
        number = issue["number"]
        effective = ([inline_current[number]] if inline_current[number] is not None
                     else structural_by_number.get(number, []))
        missing = [n for n in effective if statuses[n][0] == "missing"]
        unknown = [n for n in effective if statuses[n][0] == "unknown"]
        if missing:
            refs = ", ".join(f"#{n}" for n in missing)
            print(f"::warning::stale_blocked_guard: #{number} называет {refs}, "
                  "но такого issue/PR нет — протухание не подтверждено, метка "
                  "не тронута (issue #1211, третье состояние)",
                  file=sys.stderr)
            lines.append(f"❓ #{number}: названный блокер {refs} не существует — не подтверждено, метка не тронута")
        elif unknown:
            refs = ", ".join(f"#{n}" for n in unknown)
            print(f"::warning::stale_blocked_guard: #{number} состояние {refs} "
                  "не удалось прочитать — пропущено, не считается ни целым, "
                  "ни протухшим",
                  file=sys.stderr)
            lines.append(f"❓ #{number}: состояние {refs} не удалось прочитать — не подтверждено, метка не тронута")

    violations = find_stale_blocked(issues, closed_numbers, structural_by_number)
    if not violations:
        if lines:
            return lines
        return [f"💗 blocked: протухших меток не найдено ({len(issues)} issue с меткой blocked проверено)"]

    by_number = {issue["number"]: issue for issue in issues}
    states = {number: data for number, (_, data) in statuses.items()}
    for violation in violations:
        number = violation["number"]
        try:
            remove_label(repo, number)
        except RuntimeError as error:
            # Снятие не удалось (сеть/права) — тот же класс, что провал
            # remove_label в waiting_owner_guard.py: не тонем молча, красная
            # строка отчёта плюс эскалация тем же каналом, что раньше несла
            # само протухание (метка так и осталась висеть без газа). Дедуп
            # эскалации на эпизод (already_escalated) сохранён здесь ЖЕ:
            # повторяющийся сетевой отказ не должен слать Telegram каждые
            # 15 минут (тот же приём, что был у всего модуля до #1157).
            print(f"::warning::метка blocked не снята с #{number}: {error}", file=sys.stderr)
            issue = by_number[number]
            texts = [issue.get("body") or ""] + issue["comments_text"]
            target = escalation_target(violation)
            if already_escalated(texts, target):
                lines.append(f"🔇 {violation_text(violation)} — метка НЕ снята "
                             f"автоматически ({error}); уже эскалировано в этом эпизоде")
            else:
                delivered = escalate(repo, number, escalation_text(violation))
                lines.append(f"🚨 {violation_text(violation)} — метка НЕ снята "
                             f"автоматически ({error}); эскалировано (сигнал: {delivered})")
            continue
        try:
            pulse_guard.post_issue_comment(repo, number, removal_comment_text(violation, states))
        except RuntimeError as error:
            print(f"::warning::след снятия не оставлен в #{number}: {error}", file=sys.stderr)
        lines.append(f"✅ метка `blocked` снята автоматически — {violation_text(violation)}")
    return lines


def post_fact_comment(repo: str, number: int, text: str) -> tuple[bool, str]:
    """Доставка комментария-факта непомеченной issue (второе ревью PR #1216,
    «провал доставки падает только в лог»): сам POST, а при его отказе —
    тот же канал эскалации, что у помеченного пути (`pulse_guard.escalate`:
    повтор комментария + Telegram). Модуль уже доказал (#268), что лог этого
    job'а каналом не является — отказ доставки не тонет только в нём.
    Возвращает (оставлен_ли_комментарий, деталь_отказа_с_отчётом_эскалации)."""
    try:
        pulse_guard.post_issue_comment(repo, number, text)
        return True, ""
    except RuntimeError as error:
        print(f"::warning::stale_blocked_guard: комментарий не оставлен в #{number}: "
              f"{error} — доставляюсь тем же каналом, что помеченный путь "
              "(pulse_guard.escalate)", file=sys.stderr)
        delivered = escalate(repo, number, text)
        return False, f"{error}; эскалировано тем же каналом (сигнал: {delivered})"


def unlabeled_stale_check(repo: str) -> list[str]:
    """Проводка по ВСЕМУ пулу (issue #1211), в отличие от `stale_blocked_check`
    (только issue с меткой `blocked`): issue БЕЗ метки, чей текст (структурное
    поле «Чем блокируется» ЛИБО инлайн-маркер прозы) называет закрытого/
    несуществующего блокера. Ни один найденный случай не несёт тормоза
    (метки нет) — единственное действие гвардии здесь — комментарий-факт,
    идемпотентный на эпизод (`already_marked`). Issue с меткой `blocked`
    пропускается целиком — её путь уже отработан `stale_blocked_check`,
    не дублируем комментарии на одну и ту же issue двумя путями.

    Второе ревью PR #1216: неузнаваемое поле и инлайн-цель на одной issue
    НЕ исключают друг друга — обе проверки проходят, каждая со своим
    маркером эпизода (дедуп у каждого свой, спама нет)."""
    issues = task_deps.fetch_pool(repo, label="task", include_body=True)

    candidates: dict[int, dict] = {}
    referenced: set[int] = set()
    for issue in issues:
        labels = {label["name"] for label in issue.get("labels") or []}
        if BLOCKED_LABEL in labels:
            continue
        number = issue["number"]
        declared = declared_targets(number, issue.get("body") or "")
        if declared["unrecognized"] or declared["targets"]:
            candidates[number] = declared
            if declared["targets"]:
                referenced.update(declared["targets"])

    if not candidates:
        return [f"💗 unlabeled: протухших объявлений не найдено ({len(issues)} задач пула проверено)"]

    target_states: dict[int, tuple[str, dict]] = {n: target_status(repo, n) for n in referenced}
    issue_by_number = {issue["number"]: issue for issue in issues}
    # Комментарии читаются ЛЕНИВО и ОДИН раз на issue: неузнаваемое поле и
    # инлайн-цель на одной и той же issue используют один и тот же список —
    # два fetching'а одной страницы были бы просто лишним вызовом gh.
    comments_cache: dict[int, list[str]] = {}

    def comments_of(num: int) -> list[str]:
        if num not in comments_cache:
            comments_cache[num] = fetch_comments_text(repo, num)
        return comments_cache[num]

    lines: list[str] = []
    for number, declared in sorted(candidates.items()):
        # Доводка ревью PR #1216, пункт 2: у ❓-исхода канал доставки адресату
        # (идемпотентный комментарий, дедуп на эпизод — телом эпизода служит
        # сам неразборчивый текст поля), а не только лог прогона. ❓-строка
        # остаётся честно красной (тело всё ещё не по схеме), но путь к
        # зелёному назван дословно в самом комментарии (газ: кто правит, по
        # какому сигналу, когда зеленеет). `continue` НЕТ: на той же issue
        # может быть разборный инлайн-маркер — он проверяется ниже.
        if declared["unrecognized"]:
            body = issue_by_number[number].get("body") or ""
            value = unrecognized_field_value(body)
            if already_marked(comments_of(number), UNRECOGNIZED_FIELD_MARKER, value):
                lines.append(f"💤 #{number}: объявление блокера не разобрано — уже сообщено в этом эпизоде")
            else:
                posted, failure = post_fact_comment(
                    repo, number,
                    unrecognized_field_comment_text(
                        value, last_inline_marker_target(number, body)))
                if posted:
                    print(f"::warning::stale_blocked_guard: #{number} поле «Чем блокируется» "
                          "заполнено, но текст не разбирается ни как «ничем», ни как чистый "
                          "список номеров — оставлен комментарий с разборимой формой "
                          "(issue #1211/#1215)",
                          file=sys.stderr)
                    lines.append(f"❓ #{number}: объявление блокера не разобрано — оставлен комментарий с разборимой формой")
                else:
                    lines.append(f"❓ #{number}: объявление блокера не разобрано — "
                                 f"комментарий не оставлен: {failure}")

        targets = declared["targets"]
        if not targets:
            continue
        statuses = {n: target_states[n][0] for n in targets}
        unknown_targets = [n for n, s in statuses.items() if s == "unknown"]
        if unknown_targets:
            refs = ", ".join(f"#{n}" for n in unknown_targets)
            print(f"::warning::stale_blocked_guard: #{number} состояние {refs} не "
                  "удалось прочитать — пропущено, не считается ни целым, ни протухшим",
                  file=sys.stderr)
            lines.append(f"❓ #{number}: состояние {refs} не удалось прочитать — не подтверждено")
            continue

        missing_targets = [n for n, s in statuses.items() if s == "missing"]
        if missing_targets:
            violation = {"number": number, "missing_refs": missing_targets}
            target = ",".join(f"#{n}" for n in missing_targets)
            if already_marked(comments_of(number), MISSING_TARGET_MARKER, target):
                lines.append(f"💤 #{number}: несуществующий блокер ({target}) — уже сообщено в этом эпизоде")
                continue
            posted, failure = post_fact_comment(repo, number, missing_target_comment_text(violation))
            if posted:
                lines.append(f"✅ #{number}: несуществующий блокер ({target}) — оставлен комментарий-факт")
            else:
                lines.append(f"🚨 #{number}: несуществующий блокер ({target}) — комментарий не оставлен: {failure}")
            continue

        if all(s == "closed" for s in statuses.values()):
            violation = {"number": number, "stale_refs": targets}
            target = escalation_target(violation)
            if already_marked(comments_of(number), UNLABELED_STALE_MARKER, target):
                lines.append(f"💤 #{number}: протухшее объявление ({target}) — уже сообщено в этом эпизоде")
                continue
            states = {n: target_states[n][1] for n in targets}
            posted, failure = post_fact_comment(
                repo, number, unlabeled_stale_comment_text(violation, states))
            if posted:
                lines.append(f"✅ #{number}: протухшее объявление ({target}) — оставлен комментарий-факт")
            else:
                lines.append(f"🚨 #{number}: протухшее объявление ({target}) — комментарий не оставлен: {failure}")
        # иначе — хотя бы один из объявленных блокеров ещё открыт, объявление
        # легитимно (семантика «И», см. докстринг модуля/тест на #768) — молчим.

    if not lines:
        return [f"💗 unlabeled: протухших объявлений не найдено ({len(issues)} задач пула, "
                f"{len(candidates)} с объявленным блокером — все легитимны)"]
    return lines


def main() -> int:
    repo = os.environ.get("GITHUB_REPOSITORY", "mytab0r/edge-harness")
    lines: list[str] = []
    # Доводка ревью PR #1216 (пункт 1): пути исполняются последовательно, и
    # крах ОДНОГО не должен хоронить отчёт ВТОРОГО — падение целого пути
    # даёт 🚨-строку и красный шаг, второй путь досчитывается. Не
    # RuntimeError, а Exception: цель изоляции — «любой отказ одного
    # обхода не отменяет второй обход», красный шаг всё равно остаётся
    # (continue-on-error в orchestra.yml), тишины из этого не получается.
    for name, sweep in (("blocked (метки)", stale_blocked_check),
                        ("unlabeled (проза пула)", unlabeled_stale_check)):
        try:
            lines += sweep(repo)
        except Exception as error:  # noqa: BLE001 — см. комментарий выше
            print(f"::error::stale_blocked_guard: обход «{name}» упал целиком: {error!r}",
                  file=sys.stderr)
            lines.append(f"🚨 обход «{name}» упал целиком ({error}) — "
                         "отчёт второго обхода не должен погибнуть вместе с ним")
    for line in lines:
        print(line)
    # 💗 — холостой ход, ✅ — находка УЖЕ ПОЧИНЕНА этим же прогоном (метка
    # снята/комментарий-факт оставлен) — оба зелёные. 💤 — тот же эпизод уже
    # сообщён раньше, новых действий нет — здоровый дедуп, тоже зелёный (issue
    # #1211: повтор не спам, а признак, что «не спамь» работает). 🚨 — само
    # действие (снятие метки/комментарий) не удалось (сеть/права) ИЛИ весь
    # обход упал (изоляция путей выше) — красный шаг остаётся видимым при
    # continue-on-error (находка ревью #333/#336), это и есть газ для отказа
    # газа. ❓ — третье состояние (issue #1211/check_result.py): состояние
    # цели не удалось прочитать (на ОБЕИХ сторонах) ИЛИ текст поля не
    # разобран (на непомеченной; у помеченной поле-причина без инлайна —
    # ручной случай, см. «Честная граница доводки»); не выглядит как
    # «связь цела»,
    # красит шаг, не молчит; у «поле не разобрано» есть доставленный адресату
    # комментарий-газ (UNRECOGNIZED_FIELD_MARKER), у «метки» — названный в
    # докстринге ручной газ (правка формулировки тем, кто задачу прочтёт).
    return 0 if all(line.startswith(("💗", "✅", "💤")) for line in lines) else 1


if __name__ == "__main__":
    sys.exit(main())
