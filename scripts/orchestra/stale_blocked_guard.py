# Значения поля («ничем»/«ничего», возможная концевая пунктуация человека) —
# ЕДИНСТВЕННЫЙ явный «блокеров нет» ответ, принимаемый structural_field_targets.
_EMPTY_ANSWER_RE = re.compile(r"^(?:ничем|ничего|нечем)[.!]?$", re.IGNORECASE)

# Строгий список номеров — ТОЛЬКО «#N» через пробел, без единого лишнего
# слова (issue #1215: declared_deps.form_field_numbers щедро вытягивает
# числа из ЛЮБОГО текста поля, включая пояснение после «ничего», живые
# ложные срабатывания #768/#971 — см. докстринг модуля).
_STRICT_NUMBER_LIST_RE = re.compile(r"^#\d+(?:\s+#\d+)*$")


def _form_field_value(body: str) -> str | None:
    """ЕДИНСТВЕННОЕ место извлечения значения поля «Чем блокируется» из тела
    (те же объекты `declared_deps._FORM_FIELD_RE`/`_strip_quoted_noise`, не
    вторая копия регэкспа). `None` — поля нет вовсе; иначе — «сырое» значение
    (без `.strip()`), которое строгий разбор `structural_field_targets` и
    отчёт `unrecognized_field_value` читают ОДНИМ путём."""
    match = declared_deps._FORM_FIELD_RE.search(declared_deps._strip_quoted_noise(body or ""))
    if not match:
        return None
    return match.group(1)


def structural_field_targets(body: str) -> tuple[str, list[int] | None]:
    """Консервативное чтение структурного поля формы «Чем блокируется» —
    переиспользует ТЕ ЖЕ объекты `declared_deps._FORM_FIELD_RE`/
    `_strip_quoted_noise` (через `_form_field_value`, не вторая копия
    регэкспа), но требует СТРОГОГО ответа: явно «ничем»/«ничего» (плюс
    необязательная концевая пунктуация) ИЛИ СПИСОК «#N #M» и больше ничего.
    Любой другой непустой текст — `"unrecognized"` (третье состояние, не
    молчаливое доверие и не молчаливый пропуск — issue #1211/#1215).

    Возвращает (`"absent"`, None) — поля нет вовсе; (`"empty"`, []) —
    явный ответ «нет блокеров»; (`"declared"`, [...]) — чистый список
    номеров; (`"unrecognized"`, None) — поле заполнено, но текст не по
    строгой форме, разбирать не пытаемся."""
    raw = _form_field_value(body)
    if raw is None:
        return "absent", None
    value = raw.strip()
    if not value or _EMPTY_ANSWER_RE.match(value):
        return "empty", []
    if _STRICT_NUMBER_LIST_RE.match(value):
        return "declared", [int(n) for n in re.findall(r"#(\d+)", value)]
    return "unrecognized", None


def declared_targets(number: int, body: str) -> dict:
    """Единый источник кандидата на ТЕКУЩЕГО блокера issue `number` по телу
    (issue #1211). ОДНО правило старшинства с помеченным путём (второе
    ревью PR #1216, «два разных правила старшинства в одном модуле»):
    разборный ИНЛАЙН-МАРКЕР старше структурного поля — на этой поверхности
    он тоже самое свежее договорное высказывание о причине (последняя
    строка тела, `last_inline_marker_target`), а поле формы — ответ схемы,
    заполненный при заведении. Неузнаваемое поле инлайн НЕ глушит: битое
    поле и живая строка «БЛОКИРУЕТСЯ: #897» в одном теле дают ОБА факта —
    проверку #897 и ❓-комментарий о поле (ниже, `unlabeled_stale_check`),
    а не молчаливую потерю протухшего объявления за неразборчивой формой.

    Возвращает `{"form": "structural"|"inline"|None, "targets": [...]|None,
    "unrecognized": bool}` — `targets` пуст (`[]`), если поле явно отвечает
    «ничем» (и инлайна нет); `None`, если источника нет вовсе;
    `unrecognized=True` — поле заполнено не по схеме (факт доставляется
    отдельно и не мешает проверке инлайн-цели)."""
    kind, structural = structural_field_targets(body)
    inline = last_inline_marker_target(number, body)
    unrecognized = kind == "unrecognized"
    if inline is not None:
        return {"form": "inline", "targets": [inline], "unrecognized": unrecognized}
    if kind == "declared" and structural:
        return {"form": "structural", "targets": structural, "unrecognized": False}
    # Поле отсутствует/явно пустое/неразборчивое, инлайн-маркера нет.
    return {"form": "structural" if unrecognized else None,
            "targets": None, "unrecognized": unrecognized}


# Маркеры эпизодов НОВЫХ исходов (по образцу STALE_ESCALATE_MARKER выше) —
# СВОИ, не переиспользуют STALE_ESCALATE_MARKER: три разных факта («метка
# протухла», «текст без метки протух», «цель не существует») обязаны иметь
# разные, самостоятельно узнаваемые следы (AGENTS.md «Алерт не гадает» —
# склеивание в один маркер сделало бы дедуп неотличимым между фактами).
UNLABELED_STALE_MARKER = "[протухшее объявление:"
MISSING_TARGET_MARKER = "[несуществующий блокер:"
# Четвёртый факт (доводка ревью PR #1216, пункт 2): поле «Чем блокируется»
# заполнено, но не по схеме — гвардия его не читает. Свой маркер, потому что
# факт свой (тело не разобрано), а не «протухло»/«не существует»: дедуп по
# чужому маркеру погасил бы новый факт.
UNRECOGNIZED_FIELD_MARKER = "[неразборчивое поле блокировки:"

# Потолок тела эпизода для UNRECOGNIZED_FIELD_MARKER (жирный непарсируемый
# текст поля целиком в маркер не тащим).
_UNRECOGNIZED_TARGET_MAX = 200


def unlabeled_stale_comment_text(violation: dict, states: dict[int, dict]) -> str:
    """Комментарий-факт для issue БЕЗ метки `blocked` (issue #1211): снимать
    нечего (тормоза нет), поэтому только называет факт, чтобы следующий
    читатель не отказался от задачи по протухшей причине."""
    parts = []
    for number in violation["stale_refs"]:
        data = states.get(number) or {}
        closed_at = data.get("closed_at") or "момент неизвестен (поле не вернулось)"
        parts.append(f"#{number} закрыт {closed_at}")
    refs_text = "; ".join(parts)
    return (
        f"{UNLABELED_STALE_MARKER} {escalation_target(violation)}]\n"
        f"ℹ️ объявленный блокер устарел (stale_blocked_guard, #1211): {refs_text}. "
        "Метки `blocked` на этой задаче нет — автоматически снимать нечего, но "
        "прежнее объявление «Чем блокируется»/«БЛОКИРУЕТСЯ:» больше не описывает "
        "реальную зависимость — не считай задачу недоступной по этой причине; "
        "поправь формулировку в теле вручную, когда возьмёшь задачу."
    )


def missing_target_comment_text(violation: dict) -> str:
    """Комментарий-факт: названный блокер не существует вовсе (не «закрыт», а
    физически нет issue/PR с таким номером) — issue #1211, третий исход,
    отдельный от «закрыт» (AGENTS.md «Алерт не гадает»: два разных факта,
    два разных текста)."""
    refs = ", ".join(f"#{n}" for n in violation["missing_refs"])
    return (
        f"{MISSING_TARGET_MARKER} {','.join(f'#{n}' for n in violation['missing_refs'])}]\n"
        f"⚠️ объявленный блокер не существует (stale_blocked_guard, #1211): {refs} "
        "— issue/PR с таким номером в репозитории нет. Проверь формулировку "
        "«Чем блокируется»/«БЛОКИРУЕТСЯ:» вручную — вероятная опечатка в номере."
    )


def unrecognized_field_value(body: str) -> str:
    """Значение поля «Чем блокируется» как есть — тело эпизода для дедупа
    `UNRECOGNIZED_FIELD_MARKER`: тот же неразборчивый текст даёт тот же маркер
    (повторный прогон не спамит), правка текста автором открывает новый
    эпизод (факт «тело не разобрано» уже другой). Закрывающая скобка
    вырезается (сломала бы разбор маркера-скобки `marker_body`), пробелы
    нормализованы, потолок `_UNRECOGNIZED_TARGET_MAX`. Использует ТЕ ЖЕ
    объекты регэкспа, что `structural_field_targets` (одно место извлечения
    значения — `_form_field_value`), второй копии поля нет."""
    value = _form_field_value(body)
    if value is None:
        return ""
    value = re.sub(r"\s+", " ", value.replace("]", ")")).strip()
    return value[:_UNRECOGNIZED_TARGET_MAX]


def unrecognized_field_comment_text(value: str, inline_target: int | None = None) -> str:
    """Комментарий для исхода ❓ «поле не разобрано» (доводка ревью PR #1216,
    пункт 2): у исхода появился канал доставки адресату, а не только лог
    прогона, который этот job уже однажды доказал нечитаемым (#268). Текст
    называет ГАЗ дословно: кто правит (тот, кто следующим возьмёт или
    прочтёт задачу), по какому сигналу (этот комментарий) и при каком
    условии шаг зеленеет (поле приведено к разборимой форме) — AGENTS.md
    «Тормоз без газа не принимается».

    `inline_target` (второе ревью PR #1216, старшинство источников): когда
    в теле помимо битого поля найден разборный инлайн-маркер, комментарий
    называет его отдельной фразой — читатель видит, что объявление не
    потеряно и проверяется, а не «гвардия о нём не знает»."""
    inline_note = (
        f"\n\nРазборный инлайн-маркер в теле при этом найден («БЛОКИРУЕТСЯ: "
        f"#{inline_target}») — он старше неразборчивого поля и проверяется "
        "этой же гвардией отдельно; потеряно только само поле."
        if inline_target is not None else ""
    )
    return (
        f"{UNRECOGNIZED_FIELD_MARKER} {value}]\n"
        "❓ гвардии stale_blocked_guard (#1211) не удалось разобрать ответ поля "
        "«Чем блокируется»: текст не читается ни как явное «ничем»/«ничего», ни как "
        "чистый список «#N #M» — а других машиночитаемых форм У ПОЛЯ гвардия нет "
        "(структурное поле — ответ схемы формы, его форма строже щедрого "
        "извлечения чисел, issue #1215). Пока поле не по схеме, объявление ПОЛЕМ "
        "не проверяется вовсе — протухание по нему неотслеживаемо. Газ: приведи "
        "ответ поля к одной из двух форм («ничем»/«ничего» или «#N #M») — "
        "следующий прогон гвардии (каждые 15 минут) снова читает поле, и красный "
        "шаг зеленеет. Правит поле тот, кто следующим возьмёт или прочтёт задачу; "
        f"сигнал — этот комментарий.{inline_note}"
    )


