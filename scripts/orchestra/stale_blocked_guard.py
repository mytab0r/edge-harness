BLOCKED_LABEL = "blocked"

# Стебли маркера блокировки — ОДНО место правды ФОРМ (критерий 1 задачи
# #1211). Из этой константы собираются ДВА скомпилированных регэкспа ниже:
# позиция/двоеточие — политика ПОВЕРХНОСТИ, стебли — общие. Второй список
# стеблей в другом месте репозитория — дефект (правило «Одно место правды»).
_MARKER_STEMS = r"(?:Блокирован[а-я]*|Заблокирован[а-я]*|Блокируется|Причина блокировки)"

# СТРОГИЙ — скан тела+КОММЕНТАРИЕВ помеченного пути (всё, где решается СНЯТИЕ
# тормоза: `stale_marker_targets`, `current_stale_marker_target`,
# `find_stale_blocked`). Позиция — НАЧАЛО СТРОКИ (находка ревью PR #336: без
# неё регэксп матчил маркер в любом месте прозы — цитата старого маркера в
# новой реплике, «задача заблокирована: #N» внутри предложения — и превращал
# гвардию в cry-wolf, собственный эскалационный комментарий гвардии цитирует
# маркер) ЛИБО сразу после конца предыдущего предложения («. » — точка и
# пробел; находка issue #938: живой комментарий #215/#258 несёт «Причина
# блокировки: #809.» ПОСЛЕДНИМ предложением абзаца без переноса строки —
# жёсткая привязка «только начало строки» не поймала бы ни одного реального
# случая этой формулировки). Ведущие пробелы и маркер маркдаун-списка
# («- »/«* ») НЕ допускаются, двоеточие ОБЯЗАТЕЛЬНО.
#
# Блокирующая находка ревью PR #1216 (второй раунд): ослабление из #1211
# (списочный префикс, разрешительные ведущие пробелы, опциональное двоеточие),
# применённое к ОДНОМУ регэкспу на оба пути, утекло сюда — и комментарий
# помеченной issue, ЦИТИРУЮЩИЙ чужую строку зависимости с начала строки
# («- Заблокировано #80 (…) ← цитата из чужого тела»), становился «текущей
# причиной» метки (`current_stale_marker_target` берёт последний текст с
# матчем); названный в цитате закрытый номер — и гвардия сама снимает живой
# тормоз с чужой причиной в следе. Класс не гипотетичен: #1162/#1121 — две
# цитаты маркеров в обсуждениях за одну неделю; раньше их спасала позиция
# цитаты в середине строки. Здесь (там, где снимается тормоз) — только
# строгая позиция; расширенные формы живут в POOL_MARKER_RE для тел пула.
STALE_MARKER_RE = re.compile(
    r"(?:^|(?<=\.\s))" + _MARKER_STEMS + r"\s*:\s*#(\d+)",
    re.IGNORECASE | re.MULTILINE)

# РАСШИРЕННЫЙ — чтение ТЕЛ пула в `declared_targets` (unlabeled-путь,
# issue #1211; комментарии этим регэкспом не читаются вовсе — см.
# «Стоимость обхода»: на живом пуле маркер объявлений живёт в теле).
# Живые формы тел: «БЛОКИРУЕТСЯ: #N» (стем «Блокируется», последняя непустая
# строка, конвенция ai_review.BLOCKED_BY_RE — живые #1016/#976/#959);
# «Заблокировано #N» БЕЗ двоеточия внутри маркдаун-списка (стем
# «Заблокирован[а-я]*» — живой #86, «- Заблокировано #80 (…)» под заголовком
# «## Зависимости»). Отсюда: маркер списка «[-*]\s+» и ведущие пробелы
# допущены, двоеточие НЕОБЯЗАТЕЛЬНО (`:?`). Позиционный риск цитирования
# в теле (тот же класс #1162/#1121) снимается правилом ПОСЛЕДНЕГО матча
# (`last_inline_marker_target`): договорная форма живёт последней строкой
# тела, цитаты чужих маркеров — раньше.
POOL_MARKER_RE = re.compile(
    r"(?:^[ \t]*(?:[-*]\s+)?|(?<=\.\s))\s*" + _MARKER_STEMS + r"\s*:?\s*#(\d+)",
    re.IGNORECASE | re.MULTILINE)

# Маркер эскалации ЭТОЙ гвардии (не путать со STALE_MARKER_RE — тем маркером
# воркер называет причину блокировки; этим гвардия называет свою находку).
# Форма — как DRIFT_MARKER/PAUSE_MARKER: скобочная строка, в прозе так не
# пишут, тело — цель эпизода (набор протухших ссылок), закрывается «]».
STALE_ESCALATE_MARKER = "[протухшая блокировка:"


