#!/usr/bin/env bash
# Гвардия «состав карантина доезжает до лога деплоя» (issue #1379).
#
# Класс: «карантин пуст» и «состав прочитать не смогли» — РАЗНЫЕ исходы, и
# второй не имеет права выглядеть как первый. Патч 0007 (#1376) изолирует
# сессию, которую билд не может перевести в текущий формат; состав изоляции до
# #1379 был недоступен прогону деплоя (console.error уходит в Workers-логи,
# таблица живёт внутри Durable Object), и владелец узнавал его только руками.
#
# Гвардия ПОВЕДЕНЧЕСКАЯ: поднимает настоящий http.server, гоняет настоящий curl
# через scripts/lib/canary_http.sh и читает настоящий вывод; «маршрут
# недоступен» — закрытый порт, а не подменённая функция (AGENTS.md, «Заглушка
# внешнего инструмента — это пересказ», #1373/PR #1380). Текстовая проверка
# исходника доказала бы орфографию, а не поведение (класс #891/#893).
#
# Что она поймала на живом коде, до всякого ревью — две штуки, обе мои:
#   1) `jq '.quarantined | length'` на теле БЕЗ поля даёт 0 (`null | length`),
#      то есть ответ `{"ok":true}` без массива выглядел как ПУСТОЙ карантин —
#      ровно silent-wrong, против которого задача. Лечение: спрашивать тип, а
#      не длину;
#   2) текст отказа содержал фразу «карантин пуст» внутри отрицания («это НЕ
#      «карантин пуст»») — grep и беглый взгляд читают её как утверждение.
#      Лечение: фраза убрана из отказов вовсе.
#
# Доказано мутациями — ИСПОЛНЕНО, не пересказано (числа в теле PR #1379).
set -euo pipefail

# Вызов ИМЕННО в этой форме — `bash <путь от корня репозитория>`, без `exec`
# и без переменной пути: осирот-детектор `scripts/lib/orphan_test_guard.py`
# распознаёт только `bash`/`sh` первым словом statement'а и резолвит второй
# аргумент относительно корня репо. Форма `exec bash "$ROOT/…"` ему не видна —
# тест считается незапускаемым ни одним workflow, и обязательная проверка
# краснеет (блокирующая находка ai-ревью PR #1399). Все соседние гвардии
# каталога зовут тесты так же; каталог исполняется из корня репозитория.
bash scripts/lib/test/quarantine-report.test.sh
