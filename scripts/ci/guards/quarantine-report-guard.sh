#!/usr/bin/env bash
# Гвардия «состав карантина доезжает до лога деплоя» (issue #1379).
#
# Класс: «карантин пуст» и «состав прочитать не смогли» — РАЗНЫЕ исходы, и
# второй не имеет права выглядеть как первый. Патч 0007 (#1376) изолирует
# сессию, которую билд не может перевести в текущий формат; состав изоляции до
# #1379 был недоступен прогону деплоя (console.error уходит в Workers-логи,
# таблица живёт внутри Durable Object), и владелец узнавал его только руками.
#
# Гвардия ПОВЕДЕНЧЕСКАЯ: поднимает настоящий HTTP-сервер, гоняет настоящий
# curl через scripts/lib/canary_http.sh и настоящий jq, читает настоящий
# вывод; «маршрут недоступен» — закрытый порт, а не подменённая функция
# (AGENTS.md, «Заглушка внешнего инструмента — это пересказ», #1373/PR #1380).
# Текстовая проверка исходника доказала бы орфографию, а не поведение
# (класс #891/#893).
#
# Что она поймала на живом коде, до всякого ревью — две штуки, обе мои:
#   1) `jq '.quarantined | length'` на теле БЕЗ поля даёт 0 (`null | length`),
#      то есть ответ `{"ok":true}` без массива выглядел как ПУСТОЙ карантин —
#      ровно silent-wrong, против которого задача. Лечение: спрашивать тип, а
#      не длину;
#   2) текст отказа содержал фразу «карантин пуст» внутри отрицания («это НЕ
#      «карантин пуст»») — grep и беглый взгляд читают её как утверждение.
#      Лечение: фраза убрана из отказов вовсе.
#
# Доказано мутациями — ИСПОЛНЕНО, не пересказано (AGENTS.md, «рецепт мутации —
# исполни, не вспоминай»). База до мутаций и после отката — «7 passed».
#   1) вернуть в quarantine_report.sh длину вместо типа:
#      `jq 'if (.quarantined | type) == "array" then (.quarantined | length)
#      else "нет-массива" end'` → `jq '.quarantined | length'` — «2 failed,
#      5 passed», краснеют
#      test_json_without_the_field_is_a_read_failure_not_an_empty_quarantine и
#      test_field_of_the_wrong_type_is_a_read_failure_too (две РАЗНЫЕ двери
#      одного класса: поля нет вовсе — и поле есть, но не массив), и в stdout
#      мутанта стоит дословно «✅ карантин пуст: ни одна сессия не осталась
#      непереведённой» на ответе `{"ok":true}` — тот самый silent-wrong;
#   2) считать неотвеченный маршрут пустым карантином (ветку отказа
#      `canary_http` заменить на `|| body='{"ok":true,"quarantined":[]}'`) —
#      «1 failed, 6 passed», краснеет
#      test_unreachable_route_is_a_read_failure_not_an_empty_quarantine, то
#      есть главная сцена задачи.
#
# Тест на pytest, а не на bash: каталог гвардий уже требует этой формы от
# соседей (canary-http-guard.sh), и ровно её понимает гейт мутационного
# доказательства (scripts/lib/mutation_claim.py::TEST_CMD_RE — узкий на
# `python -m pytest <цель> -q` СОЗНАТЕЛЬНО, чтобы тело PR не могло подсунуть
# гейту произвольную команду). Стенд на bash был бы неисполним машиной.
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml.
set -euo pipefail
pip install --quiet pytest
python -m pytest scripts/lib/test_quarantine_report.py -q
