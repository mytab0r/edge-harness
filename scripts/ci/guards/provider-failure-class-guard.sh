#!/usr/bin/env bash
# Каталожная обёртка гвардии класса отказа провайдера (#1494).
#
# Класс одной фразой: **`HTTP_404` засчитывался доказательством мёртвого id
# модели, хотя 404 не различает «такой модели нет» и «такого маршрута нет».**
#
# Замер, оплативший правило (docs/research/28-provider-chain-truth-table.md):
# пять записей цепочки из восьми отвечают HTTP 200 прямым вызовом
# `<base_url>/chat/completions` и те же пять не отвечают через `dsh`. У GLM
# вердикт был `dead_model` — «починить конфигурацию, узнать точный id модели», —
# то есть следующего агента отправляли чинить исправную запись цепочки.
#
# Проверка поведенческая: настоящий bash, настоящий `source` прод-файла,
# настоящие функции на дословных прод-формах stderr из живых прогонов. Не grep
# по исходнику: переименование функции или возвращённый `HTTP_404:` внутри
# другой ветки прошли бы текстовую проверку молча (AGENTS.md, «Поведенческий
# тест находит то, чего структурный не видит»).
set -euo pipefail
# Стенд — pytest, хотя предмет проверки на bash: тем же доводом, что у соседней
# dsh-transitive-pin-guard.sh — гейт заявления о мутации в теле PR знает ровно
# форму `python -m pytest`, а гвардия осиротевших тестов требует, чтобы каждый
# файл теста запускался workflow напрямую.
python -m pytest scripts/lib/test_provider_failure_class_guard.py -q
