#!/usr/bin/env bash
# Гвардия issue #1172 («последний барьер автономности»): механизм, который
# не может сработать никогда, потому что раньше срабатывает конкурирующее
# условие на той же величине (подпись 1), потому что распознаваемая строка
# не встречается ни в одном реальном логе (подпись 3) или потому что
# проверяемая величина всегда имеет одно значение — запись этого же тика
# (подпись 2) — ai-review нашёл три живых случая за 2026-09-13
# (PR #1089/#1104/#1114), сама недостижимость тестами не ловится (условие
# подаётся напрямую, а не через реальный путь кода). Логика и исторические
# фикстуры — scripts/orchestra/reachability_guard.py +
# test_reachability_guard.py.
#
# Мутации, доказавшие тесты (воспроизводятся правкой
# reachability_guard.py, каждая красит свой набор — см. отчёт PR #1180):
#   - граница `min_reachable < slow_threshold` заменена на безусловное
#     `if True:` (вердикт всегда «reachable»);
#   - проба гейта возвращена к одной жёсткой записи `age_minutes >= ИМЯ`
#     (находка 1 ревью PR #1180) — строгий `>`, переставленные операнды,
#     другое имя величины + юнит;
#   - проба случая 2 ослеплена (факт «тексту уходит now» всегда False или
#     тело потребителя не находится) — красит тесты случая 2, включая
#     живую проверку рабочего дерева;
#   - поиск return 1 возвращён к неограниченному хвосту (находка прочёса
#     #1184) и поиск по первому if/fi-блоку — оба воспроизводятся
#     само-мутациями внутри test_reachability_guard.py, шапка счётчиков
#     не дублирует (одно место правды).
set -euo pipefail
pip install --quiet pytest
python -m pytest scripts/orchestra/test_reachability_guard.py -q
