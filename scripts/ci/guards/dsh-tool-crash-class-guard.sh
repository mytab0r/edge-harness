#!/usr/bin/env bash
# Каталожная обёртка: крах инструмента не выдаётся за отказ провайдеров (#1470).
#
# Класс одной фразой: один локальный отказ, отпечатанный по числу провайдеров,
# считался N отказами провайдеров, и итог советовал повтор, который не может
# помочь. Живые случаи — #1315 (E2BIG, восемь «отказов» за 78 секунд) и #1467
# (обновилась транзитивная зависимость dsh, падение на старте за 0–1 секунду).
#
# Проверка поведенческая: зовёт настоящую функцию сводки на прод-форме строк
# DSH_CHAIN_OUTCOMES, включая дословную выдержку stderr из живого прогона.
set -euo pipefail
# Стенд — pytest, хотя проверяет он bash: гейт заявления о мутации знает
# ровно форму `python -m pytest`, а гвардия осиротевших тестов требует,
# чтобы каждый файл теста запускался workflow напрямую. Пара «bash-стенд +
# мост» удовлетворяла обе только дублирующим запуском (поймано красными
# прогонами PR #1468).
python -m pytest scripts/lib/test_dsh_tool_crash_class.py -q
