#!/usr/bin/env bash
# Гвардия «клиенты рук печатают тело ответа при отказе» (issue #1373).
#
# Класс тот же, что #1371 закрыл для канареек деплоя: шаг, знающий и код, и
# тело ответа, не имеет права печатать только код. Поверхность другая — руки,
# воркер, обёртки статусов журнала, — и там он жил своей жизнью:
# `curl -fsS` выбрасывал причину на каждом не-2xx.
#
# Дороже всего обошлась ВТОРАЯ копия: в scripts/lib/dsh-edge-session.sh уже
# был рукописный разбор кода и тела с тем же комментарием «БЕЗ curl -f» —
# то есть правило знали, а места правды не было. Две копии расходятся молча,
# поэтому копия убрана, а не «улучшена» (AGENTS.md, «одно место правды»).
#
# Гвардия ПОВЕДЕНЧЕСКАЯ: поднимает настоящий HTTP-сервер и зовёт настоящий
# journal_post_event из scripts/lib/journal_status.sh, читая настоящий stderr.
# Тело отказа — в прод-форме журнала (cf-worker/src/harness.ts:756,
# `{error:{code,message}}`), не выдумано. Структурные рубежи (нельзя вернуть
# голый `curl -f`; нельзя завести заглушку curl, не разбирающую `-o`) стоят
# ВТОРЫМИ и не подменяют поведенческий: свойство «такого вызова здесь нет»
# исполнением не доказывается.
#
# Доказано мутациями — ИСПОЛНЕНО, не пересказано (каждая по отдельности, с
# откатом файла между ними; база рецептов 1–7 — «8 passed», рецепта 8 — «9 passed»,
# столько же после отката):
#   1) вернуть `curl -fsS` в обёртку api журнала — «2 failed, 6 passed»:
#      краснеют test_journal_failure_prints_code_and_body (тело исчезло из
#      лога) И test_no_bare_fail_flag_outside_allowlist (вход открылся).
#      Две сразу — честно: одна правка нарушает оба рубежа, они про разное;
#   2) поднять уровень обёрток с warning до error — «1 failed, 7 passed»,
#      краснеет test_journal_failure_is_warning_not_error_inside_retry_loop:
#      ::error:: на повторяемой попытке заставляет читателя гадать;
#   3) вернуть голый `curl -f` в scripts/hands/dsh_task.sh — «1 failed,
#      7 passed», краснеет только структурный рубеж (поведенческий проверяет
#      журнал, а не руки — граница названа честно, а не замазана);
#   4) указать в ALLOWED_FAIL_FLAG несуществующий путь — «2 failed,
#      6 passed»: разрешение не переживает свою причину, и заодно открывается
#      вход для реального dsh-ci.sh;
#   5) вернуть в scripts/plugins/test/status-scripts.smoke.sh прежнюю
#      заглушку curl (она не разбирает `-o`) — «1 failed, 7 passed»,
#      краснеет test_curl_stubs_parse_outfile_or_name_why_not;
#   6) дописать в scripts/worker/task.sh `curl --fail` — «1 failed,
#      7 passed»; то же для флага на ПРОДОЛЖЕНИИ строки (`curl -sS \` +
#      `-f …`) — «1 failed, 7 passed». Оба написания прежний однострочный
#      регекп пропускал молча (проверено исполнением: на обоих он давал
#      False) — находка ai-ревью PR #1380;
#   7) дописать `DSH_EDGE_CURL="curl -fsS …"` в scripts/lib/dsh-edge-session.sh
#      — «1 failed, 7 passed»; дописать `resp=$(curl -fsS …)` в
#      scripts/hands/dsh_task.sh — «1 failed, 7 passed». Обе формы жили в
#      этом репозитории и удалены этим же PR; разбор по ТОЧНОМУ токену `curl`
#      (вторая редакция рубежа) их пропускал, хотя критерий задачи
#      `git grep -nE "curl -[a-zA-Z]*f"` ловит обе — носитель был слабее
#      правила (вторая находка ai-ревью PR #1380). Контроль на ложное
#      срабатывание исполнен отдельно: `curl -sS … | grep -f /tmp/pat` —
#      «8 passed», чужой флаг после пайпа curl'у не приписывается;
#   8) третий заход того же класса — флаг, спрятанный от СТРОЧНОГО разбора
#      (вторая блокирующая находка ai-ревью PR #1380). База здесь «9 passed»:
#      добавлен рубеж по ПЕРЕМЕННЫМ-носителям аргументов curl.
#      `DSH_EDGE_CURL_ARGS=(-f …)` одной строкой — «1 failed, 8 passed»;
#      он же разложенный на МНОГОСТРОЧНЫЙ массив — «1 failed, 8 passed»
#      (склейка незакрытой скобки, иначе значение выглядело бы пустым);
#      `curl -f` в allowlist'нутом dsh-ci.sh БЕЗ `-o` — «1 failed, 8 passed»:
#      разрешение больше не покрывает файл целиком, только строки, отвечающие
#      названной причине.
#
# Газ назван дважды: голый `curl -f` разрешён там, где тело — мусор, а не
# диагностика (скачивание релизных ассетов в файл), и заглушка curl без `-o`
# разрешена там, где она мина «сюда попадать нельзя». Каждое разрешение несёт
# ПРИЧИНУ в ALLOWED_FAIL_FLAG / ALLOWED_CURL_STUB_WITHOUT_OUTFILE.
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml.
set -euo pipefail
pip install --quiet pytest
python -m pytest scripts/lib/test_hands_http_body_guard.py -q
