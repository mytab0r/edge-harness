#!/usr/bin/env bash
# Каталожная обёртка гвардии транзитивного пина dsh (#1467).
#
# Класс одной фразой: **пины держат два верхних пакета, а их зависимости
# резолвятся каждый прогон заново — публикация в чужом реестре меняет то, что
# стоит у нас, без единого коммита.**
#
# Живой инцидент 2026-09-22: `dsh` начал падать с «user patch-layer watching
# requires the Cordis HMR service» ДО обращения к провайдеру. Конвейер слияний
# встал: ни один PR не мог получить `ai:ok`, восемь провайдеров цепочки
# «отказывали» одинаково, а итог советовал повтор, который не мог помочь
# никогда.
#
# Первый диагноз называл виновником `@deepseek-ai/cordis 4.0.4` по совпадению
# дат публикации и ОПРОВЕРГНУТ (#1481) — пин закрепил 4.0.3, падение осталось
# прежним. Класс, ради которого гвардия написана, от опровержения не исчез:
# чужая публикация по-прежнему меняет содержимое нашего job'а без коммита у
# нас, и проверять это надо по диску, а не по намерению.
#
# Проверка поведенческая (реальный каталог, реальный node внутри проверяемой
# функции, настоящий `source` прод-файла), а не grep по исходнику: вырезанное
# тело прошло бы структурный тест — AGENTS.md, «Поведенческий тест находит то,
# чего структурный не видит».
set -euo pipefail
# Стенд — pytest, хотя проверяет он bash. Так вышло дешевле всего по числу
# мест: гейт заявления о мутации в теле PR знает ровно форму
# `python -m pytest`, а гвардия осиротевших тестов требует, чтобы КАЖДЫЙ файл
# теста запускался workflow напрямую. Два bash-файла (стенд + мост к pytest)
# удовлетворяли обе только дублирующим запуском — оба ограничения поймали меня
# красными прогонами PR #1468, по одному за раз.
python -m pytest scripts/lib/test_dsh_transitive_pin_guard.py -q
