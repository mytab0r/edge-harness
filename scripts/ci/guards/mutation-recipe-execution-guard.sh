#!/usr/bin/env bash
# #1194: рецепт мутации, доказанный ИСПОЛНЕНИЕМ, а не памятью.
#
# scripts/lib/mutation_recipe_guard.py — опциональный (opt-in) формат
# MUTATION-PROOF для комментариев/PR-тел, заявляющих конкретный результат
# отката фикса: гвардия реально откатывает названные пути на названный
# git-ref, гонит названную команду и сверяет заявленную подстроку с
# ФАКТИЧЕСКИМ выводом — не с тем, что автор запомнил или предположил по
# аналогии (живой случай — PR #1173/#1165, issue #1194: заявленное
# «disposeCalls is 1» разошлось с фактическим «disposeCalls is 3» ровно
# на этом классе ошибки).
#
# Тесты модуля реально исполняют историческую пару коммитов main
# (d239e324~1 / d239e324, PR #1163→#1165) через фикстурный раннер
# scripts/lib/test/ingest-mutation-scenario.mjs — требуют node в
# PATH, честно пропускаются (не притворяются зелёными), если его нет.
set -euo pipefail

# checkout@v7 в repo-ci.yml не несёт fetch-depth: 0 — клон глубины 1 не
# достаёт d239e324~1, исторический тест выше молча становится skip (issue
# #1208, второй круг ai-review, ветка (б)): дотягиваем полную историю здесь,
# в самой гвардии, а не правкой общего workflow-файла (никто больше не
# зависит от глубины клона на этом шаге).
if [ "$(git rev-parse --is-shallow-repository)" = "true" ]; then
  git fetch --unshallow origin main
fi

python3 -m pytest scripts/lib/test_mutation_recipe_guard.py -q

# scan_and_verify() до этой правки не вызывалась нигде, кроме собственных
# тестов модуля (issue #1208, второй круг ai-review, ветка (в)) — «автоматическая
# подстраховка для НОВЫХ рецептов» из ADR 0023 не существовала на практике:
# любой будущий блок MUTATION-PROOF в дереве репозитория (документация,
# комментарий гвардии) никто бы не проверил. Сканируем реально закоммиченное
# дерево (git grep без ревизии — рабочая копия PR): `-l` даёт список файлов,
# `-I` не лезет в бинарники; `git grep` возвращает 1, если совпадений нет —
# это не отказ гвардии (0 блоков — валидный, самый частый случай), поэтому
# ветвим явно вместо `|| true` внутри пайплайна.
#
# Исключён test_mutation_recipe_guard.py: его строковые фикстуры (`ref:
# abc123`, `ref: HEAD~1` в тройных кавычках) проверяют САМ ПАРСЕР, а не
# заявляют факт о коде — это проверено исполнением (issue #1208): без
# исключения эти пять фикстур дают вечный unknown() на несуществующих путях
# и красят гвардию шумом, не имеющим отношения к реальным рецептам. Сам
# `mutation_recipe_guard.py` (докстринг-пример формата) исключения не
# требует — его плейсхолдерный `ref` содержит пробел и отсеивается
# `_looks_like_template_ref` внутри самого парсера.
if hits="$(git grep -lI MUTATION-PROOF -- . ':!scripts/lib/test_mutation_recipe_guard.py' 2>/dev/null)"; then
  echo "$hits" | xargs -r python3 scripts/lib/mutation_recipe_guard.py
else
  echo "mutation-recipe-guard: 0 файлов с маркером MUTATION-PROOF в дереве"
fi
