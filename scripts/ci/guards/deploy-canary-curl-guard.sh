#!/usr/bin/env bash
# Гвардия «вход в HTTP у деплоя один» (issue #1371).
#
# Закрывает ВХОД в класс, который соседняя гвардия закрывает по поведению:
# canary-http-guard.sh держит поведение библиотеки (реальный сервер, реальный
# curl, реальный вывод), эта — то, что мимо библиотеки в deploy-dsh-edge.yml
# ходить нельзя. Без неё перевод шести шагов на canary_http остался бы
# починенным СЛУЧАЕМ: следующий агент, добавляя седьмую канарейку, написал бы
# привычное `curl -fsS`, и отказ снова пришёл бы без причины — ровно то, что
# стоило часа гипотез на прогоне 35387441612.
#
# Проверка читает файл, а не исполняет его, и это осознанно: свойство «голого
# curl здесь нет» нельзя доказать исполнением — несуществующий шаг не
# исполняется. Правило про ложно-зелёные структурные гвардии (#891/#893) не
# нарушено: там структурная проверка ПОДМЕНЯЛА проверку поведения, здесь
# поведение уже проверено соседней гвардией.
#
# Доказано мутациями — ИСПОЛНЕНО, не пересказано (каждая по отдельности,
# с откатом файла между ними):
#   1) вернуть `curl -sL -o /dev/null -w '%{http_code}'` в шаг «Канарейка
#      прода» — «1 failed, 2 passed», краснеет test_no_raw_curl_in_deploy_steps;
#   2) переставить `source` ПОСЛЕ первого вызова в шаге «Канарейка после
#      автооткота» (собственная ошибка первой итерации PR #1372, которая в
#      прогоне дала бы «canary_probe: command not found») — «1 failed,
#      2 passed», краснеет
#      test_every_step_using_the_library_sources_it_before_first_call;
#   3) подключить библиотеку относительным путём `./scripts/lib/...` —
#      «1 failed, 2 passed», краснеет
#      test_library_is_sourced_by_workspace_path_not_by_relative_guess.
# База до мутаций и после отката — «3 passed».
#
# Газ назван (AGENTS.md, «тормоз без газа не принимается»): шагу, которому
# голый curl действительно нужен, — имя и причина в ALLOWED_RAW_CURL внутри
# гвардии. Сейчас словарь пуст, потому что таких шагов нет.
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml —
# ci-guard-registration.sh замораживает список рукописных шагов, новый шаг
# здесь провалил бы её.
set -euo pipefail
pip install --quiet pytest pyyaml
python -m pytest scripts/lib/test_deploy_canary_curl_guard.py -q
