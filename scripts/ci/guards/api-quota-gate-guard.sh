#!/usr/bin/env bash
# Класс «шаг workflow читает GitHub API мимо гейта квоты» (#1437).
#
# Предохранитель #454 прикручивался к отдельным дорогим шагам вручную, и
# этого не видно ни из одного места: на 2026-09-22 гейт стоял у 1 шага из 30
# читателей API. Живой результат — прогон 35715554412 (PR #1449): шаг
# инвариантов гейт корректно пропустил, а обязательная проверка `test` всё
# равно покраснела на соседнем шаге, который про гейт не знал (HTTP 403
# «rate limit exceeded for installation»).
#
# Гвардия поведенческая: разбирает НАСТОЯЩИЕ .github/workflows/*.yml и
# считает долг числом. Реестр ALLOWED_UNGATED_API_STEPS с причиной на каждую
# запись — газ, а мёртвая запись (шаг закрыли или переименовали) красит так
# же, как незакрытый шаг: реестр не имеет права врать про размер долга.
set -euo pipefail
pip install --quiet pytest pyyaml
python -m pytest scripts/lib/test_api_quota_gate_guard.py -q
python scripts/lib/api_quota_gate_guard.py
