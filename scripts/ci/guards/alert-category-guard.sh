#!/usr/bin/env bash
# Класс «сигнал владельцу без категории» (#1461).
#
# Всё, что уходит владельцу в Telegram, шло одним потоком: решение, которого
# от него ждут, стояло вперемешку с «деплой откатился». Категория теперь
# обязательный именованный аргумент отправителя, но рантайм ловит только
# исполнившуюся строку — а сигналы уходят из редких веток (пульс не тикает,
# предохранитель сработал), и красный прогон случился бы у владельца в чате,
# а не в CI. Отсюда статическая проверка по исходнику, разбором AST.
#
# Плюс сверка трёх языковых копий реестра (Python — канон, bash для task.sh,
# TypeScript для воркера): расхождение иначе прошло бы зелёным, как уже было
# на формате callback_data решения владельца (#254).
set -euo pipefail
pip install --quiet pytest
python -m pytest scripts/lib/test_alert_category.py scripts/lib/test_alert_category_sync.py \
                 scripts/lib/test_alert_category_guard.py -q
python scripts/lib/alert_category_guard.py
