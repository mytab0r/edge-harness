#!/usr/bin/env bash
# Гвардия «немигрируемая сессия изолируется, а не роняет морду» (issue #1376).
#
# Живой случай: прогон deploy-dsh-edge.yml 35441352792 (2026-09-19). Апстримный
# postInitialize коммитит апгрейд формата одной транзакцией и сам пишет в
# комментарии: «An incompatible later session must also roll back earlier
# sessions». Одна историческая сессия v2, чей первый surface-евент стоит раньше
# первого step/start, не давала подняться ВСЕМУ Durable Object — каждый запрос
# отвечал 500, канарейка краснела, автооткат возвращал 0.14.1. Причина сутки
# была невидима: в лог уходил голый код 500 без тела (закрыто #1371/#1372).
#
# Решение и его цена — docs/decisions/0027-quarantine-unmigratable-session.md.
#
# Гвардия ПОВЕДЕНЧЕСКАЯ: исполняет РЕАЛЬНЫЙ текст патча
# dsh-edge/patches/0007-quarantine-unmigratable-session.patch, восстановленный
# из хунков диффа (пост-патчевый текст, а не пересказ), против стаба
# prepareMigration. Пересказанный метод зеленел бы и после того, как патч уехал.
#
# Доказано мутациями — ИСПОЛНЕНО, не пересказано (каждая по отдельности, с
# откатом файла патча между ними):
#   1) убрать re-throw чужого класса (`if (!(error instanceof
#      SessionFormatUnsupportedMigrationError)) throw error`) — «6 passed,
#      1 failed», краснеет «порча по-прежнему валит старт»: повреждение данных
#      стало бы тихим пропуском;
#   2) включить rebuild при непустом карантине (`refused.size === 0 &&` долой) —
#      «6 passed, 1 failed», краснеет «правки существующего метода на месте»:
#      путь rebuild копирует только строки текущей версии и дропает старую
#      таблицу, то есть стёр бы события карантинной сессии;
#   3) убрать `DELETE FROM dsh_edge_quarantined_sessions` — «6 passed, 1 failed»,
#      краснеет «список карантина переписывается целиком даже когда он пуст»:
#      запись пережила бы свою причину, и починенная сессия навсегда осталась бы
#      «карантинной» — тормоз без газа.
# База до мутаций и после отката — «7 passed».
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml —
# ci-guard-registration.sh замораживает список рукописных шагов, новый шаг
# здесь провалил бы её.
set -euo pipefail
node --test dsh-edge/test/quarantine-unmigratable.test.mjs
