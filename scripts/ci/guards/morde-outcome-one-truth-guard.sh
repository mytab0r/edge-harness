#!/usr/bin/env bash
# Гвардия единого места правды по исходу вызова морды (issue #1433).
#
# Класс: каждый вызывающий классифицировал отказ морды СВОИМ рукописным
# правилом. Правил было три, все написаны по отдельной аварии, и ни одно не
# знало про остальные:
#
#   scheduler.py  if "session-not-found" in str(error)   — архив (#119)
#   scheduler.py  if "HTTP 404" in str(error)            — заметки-итоги (#480)
#   scheduler.py  SessionFormatUnsupportedMigrationError — добавлено #1430
#
# Цена, оплаченная за одни сутки 2026-09-21/22: архив не знал про
# неподдерживаемый формат сессии и ждал повтора, которого не будет никогда;
# прогон orchestra краснел; pulse_guard читал красноту как «пульсы
# пропадали»; владельцу уходило «конвейер мёртв» при живом конвейере, который
# в те же минуты сливал PR. Три аварии — три починки по одной функции, класс
# не закрывался, потому что различение жило копиями.
#
# Гвардия держит две стороны сразу, и это важно: проверка «копий нет» зеленеет
# и тогда, когда различения не осталось ВООБЩЕ (вызывающий просто перестал
# различать исходы). Поэтому рядом стоит проверка, что общий классификатор
# реально зовут, и не меньше чем из двух мест.
#
# Доказано мутациями — ИСПОЛНЕНО на финальном дереве, не пересказано и не
# перенесено из прошлого захода. База: «14 passed» (после 5291af9 —
# тесты форм и потолка признака). Мутации 1–6 ПЕРЕИСПОЛНЕНЫ на этом
# дереве: их числа ниже — из прогона по 14 тестам; прежде они писались
# с дерева на 10 тестов (2/8, 2/8, 1/9, 2/8, 1/9, 1/9) и без этой
# оговорки расходились бы с базой — ровно тот класс, против которого
# построена эта шапка.
#   1) вернуть в scheduler.py рукописную копию с ИЗВЕСТНЫМ маркером
#      (`if "HTTP 404" in str(error):` вместо вызова общего классификатора) —
#      «2 failed, 12 passed»: краснеют обе стороны сразу, копия появилась И
#      вызовов общего классификатора стало меньше двух;
#   2) вернуть копию с НОВЫМ маркером, которого нет ни в одном списке
#      репозитория (`if "ВообщеНовыйОтказ" in str(error):`) — «2 failed,
#      12 passed». Это главная мутация: прежняя редакция гвардии зашивала
#      альтернацию известных маркеров и такую копию пропускала МОЛЧА, а
#      именно так родились все три исторические (находка ai-review PR #1434).
#      Признак теперь бесмаркерный — любое сравнение текста ошибки со
#      строковым литералом внутри тел функций, ходящих в морду, по AST;
#   3) убрать вызовы общего классификатора вовсе (перестать различать исходы)
#      — «1 failed, 13 passed», краснеет
#      test_scheduler_actually_uses_the_shared_classifier: та дыра, которую
#      первая проверка сама по себе не видит;
#   4) выбросить маркер формата сессии из TERMINAL_FAILURES — «2 failed,
#      12 passed», краснеют test_unmigratable_format_is_terminal И
#      test_terminal_outcomes_split_into_normal_and_loss (второй требует
#      `is_loss(UNMIGRATABLE)`). В прошлом заходе шапка называла только
#      первый — ai-review перегнало мутацию и получило два; здесь стоит
#      исполненное.
#   5) вернуть копию формой СРАВНЕНИЯ, а не вхождения —
#      `if str(error) == "РавенствоНовойФормыТожеНигдеНеВиденное":` внутри
#      `_archive_with_opener`, вызов классификатора не тронут — «1 failed,
#      13 passed», краснеет test_scheduler_has_no_handwritten_outcome_
#      classification. Вторая блокирующая находка того же ai-review PR
#      #1434: признак разбирал только `in`/`startswith`, а текст отказа
#      называл правило обобщённо («сравнивается со строковым литералом») —
#      честный разработчик уходил ровно в эти формы и молча возвращал
#      закрытый класс. Признак расширен: `==`/`!=` с литералом с ЛЮБОЙ
#      стороны, `re.search/match/fullmatch/findall/finditer` со строковым
#      литералом-паттерном; ложных срабатываний на реальном scheduler.py
#      ноль (живой `kind == …` в post_entity_snapshot не цепляется — имя
#      не из набора ошибки), проверено прогоном детектора по всем 11
#      функциям области;
#   6) та же копия формой регэкспа —
#      `if re.search(r"РегэксповаяФормаИНоваяКоторуюНеВидали", str(error)):` —
#      «1 failed, 13 passed», краснеет тот же тест.
#
# Честный потолок признака: паттерн, собранный заранее (`re.compile(r"…")`)
# и вызванный одним аргументом (`compiled(str(error))`), не виден — текст
# отказа называет покрытые формы, а не «любые».
#
# Отдельно — про честность этой шапки. Прошлая её редакция заявляла
# «ИСПОЛНЕНО», но три числа из четырёх не соответствовали дереву: база была
# записана как «7 passed» при восьми тестах, мутация 2 — как «1 failed,
# 6 passed» при «1 failed, 7 passed», мутация 3 называла один краснеющий
# тест вместо двух. Нашло это ai-review, перегнав мутации, а не прочитав их.
# Цена такой шапки ровно та, за которую правило «исполни, не вспоминай»
# заведено: следующий агент получает числа, не сходящиеся с его прогоном, и
# начинает сомневаться в своих руках, а не в тексте.
#
# Ширина признака закреплена не только мутациями выше, но и тестами формы —
# и это не дублирование, а страховка ИМЕННО этой шапки: она в этом файле уже
# дважды расходилась с деревом, и мутация, живущая только текстом, проверяется
# лишь тогда, когда кто-то сядет её перегонять. Исполнено: сузить признак
# обратно до `in`/`startswith` (состояние до третьего круга ревью) —
# «4 failed, 10 passed», краснеют test_the_guard_sees_a_marker_it_has_never_
# heard_of, ..._sees_equality_comparison, ..._sees_equality_with_the_literal_
# on_the_left и ..._sees_a_regular_expression_over_the_error_text.
#
# Отдельным тестом закреплён и ЧЕСТНЫЙ ПОТОЛОК, который признак объявляет
# в докстринге: заранее собранный паттерн (`re.compile`), вызванный одним
# аргументом, гвардия не видит. Пока потолок жил только прозой, он держался
# до первой правки; теперь это наблюдаемое состояние, и его изменение —
# работа, а не случайность.
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml.
set -euo pipefail
pip install --quiet pytest
python -m pytest scripts/lib/test_morde_outcome.py -q
