#!/usr/bin/env bash
# Гвардия единого места правды по исходу вызова морды (issue #1433).
#
# Класс: каждый вызывающий классифицировал отказ морды СВОИМ рукописным
# правилом. Правил было три, все написаны по отдельной аварии, и ни одно не
# знало про остальные:
#
#   scheduler.py  if "session-not-found" in str(error)   — архив (#119)
#   scheduler.py  if "HTTP 404" in str(error)            — заметки-итоги (#480)
#   scheduler.py  SessionFormatUnsupportedMigrationError — добавлено #1430
#
# Цена, оплаченная за одни сутки 2026-09-21/22: архив не знал про
# неподдерживаемый формат сессии и ждал повтора, которого не будет никогда;
# прогон orchestra краснел; pulse_guard читал красноту как «пульсы
# пропадали»; владельцу уходило «конвейер мёртв» при живом конвейере, который
# в те же минуты сливал PR. Три аварии — три починки по одной функции, класс
# не закрывался, потому что различение жило копиями.
#
# Гвардия держит две стороны сразу, и это важно: проверка «копий нет» зеленеет
# и тогда, когда различения не осталось ВООБЩЕ (вызывающий просто перестал
# различать исходы). Поэтому рядом стоит проверка, что общий классификатор
# реально зовут, и не меньше чем из двух мест.
#
# Доказано мутациями — ИСПОЛНЕНО, не пересказано. База: «7 passed».
#   1) вернуть в scheduler.py рукописное `if "HTTP 404" in str(error):` вместо
#      вызова общего классификатора — «2 failed, 5 passed»: краснеют ОБЕ
#      стороны сразу (копия появилась И вызовов общего классификатора стало
#      меньше двух). Заявлял «1 failed» по рассуждению — исполнение показало
#      другое число, и здесь стоит исполненное;
#   2) убрать вызовы morde_outcome.is_terminal вовсе (перестать различать
#      исходы) — «1 failed, 6 passed», краснеет
#      test_scheduler_actually_uses_the_shared_classifier: именно та дыра,
#      которую первая проверка сама по себе не видит;
#   3) выбросить маркер формата сессии из TERMINAL_FAILURES — «1 failed,
#      6 passed», краснеет test_unmigratable_format_is_terminal. Заявлял, что
#      покраснеет и test_adding_a_marker_reaches_every_caller_at_once — НЕТ:
#      тот подставляет свой маркер через monkeypatch и к содержимому списка
#      не привязан. Исполнение поправило рассуждение;
#   4) сплющить норму и потерю обратно (печатать строку на ЛЮБОМ терминальном
#      исходе) — «1 failed», краснеет
#      test_scheduler.py::test_append_session_notes_session_not_found_is_not_
#      hard_failure: задача без прогона воркера сессии не имеет вовсе, и
#      строка о ней топит настоящую потерю в норме. Это различение нашёл
#      живой тест, а не рассуждение — сплющено оно было мной.
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml.
set -euo pipefail
pip install --quiet pytest
python -m pytest scripts/lib/test_morde_outcome.py -q
