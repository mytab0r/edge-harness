#!/usr/bin/env bash
# Обязательный носитель критерия 3 задачи #1438: набор scripts/orchestra
# гоняется ЦЕЛИКОМ одной командой.
#
# Зачем отдельная гвардия, если те же файлы уже гоняются в repo-ci. Именно
# потому и нужна: repo-ci запускает каждый файл ОТДЕЛЬНОЙ командой (десятки
# шагов `python -m pytest <ОДИН файл> -q`), и перекрёстное протекание
# состояния в таком режиме невидимо ПО ПОСТРОЕНИЮ. Живой случай, которым
# гвардия оплачена: два теста-сторожа (`test_main_makes_zero_mutating_calls_
# on_fully_empty_queue`, `test_main_labels_old_unclaimed_task_end_to_end`)
# были КРАСНЫМИ на полном прогоне и зелёными по файлам — потому что в общем
# прогоне патч `gh` утекал мимо прод-кода (два экземпляра `pulse_guard`,
# `upstream_drift` держал непатченный) и тест уходил в живую сеть. В CI это
# не видел никто.
#
# Цена честно названа: полный прогон каталога — около 2,5 минут раннера
# против суммы одиночных. Это плата за режим, в котором класс вообще
# наблюдаем. Замечание ai-review PR #1447 названо честно: пока в
# ALLOWED_LIVE_GH остаются записи, цельный прогон делает их живые вызовы
# ВТОРОЙ раз за пуш (первый — пофайловые шаги repo-ci), то есть сжигает их
# долю квоты повторно. Газ тот же, что у списка: записи снимаются вместе с
# починкой, при пустом списке побочной траты нет вовсе.
#
# Граница носителя: гвардия гоняет scripts/orchestra и НЕ обещает шире.
# scripts/lib замерен одной командой 2026-09-22: «1110 passed, 1 skipped,
# 7 errors» — все семь ошибок одного источника, test_streamer_upstream_
# format.py требует `npm install` приватного пакета
# @deepseek-ai/dsh-session-format-v0-to-v1 и вне CI не выполняется. Зелёность
# полного прогона lib в CI этим PR не доказана, поэтому lib пока живёт в
# пофайловом режиме repo-ci; добавить его сюда можно после зелёного замера
# на CI-раннере (вскрывшиеся утечки вне файлов этого PR — отдельная задача).
#
# Доказано мутацией — ИСПОЛНЕНО (повторено на финальном дереве). База:
# «1634 passed».
#   1) снять точечный патч экземпляра pulse_guard, который держит
#      upstream_drift (в `patch_gh`, test_scheduler.py) — «2 failed,
#      1632 passed»: краснеют оба теста-сторожа. Дословный текст отказа
#      прогона: «AssertionError: тест ушёл в ЖИВОЙ GitHub: gh api
#      repos/pawaca/dsh-edge/tags?per_page=100». («Нет маршрута для:
#      repos/…/issues?state=closed&labels=auto-detected» — та же утечка на
#      дереве main, где conftest-фикстуры ещё не было: там вызов доходил до
#      фальшивого gh без маршрута, здесь гвардия перехватывает его раньше,
#      до сети.) Это ровно то состояние, в котором класс жил незамеченным,
#      и теперь оно красит гейт.
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml.
set -euo pipefail
pip install --quiet pytest pyyaml
python -m pytest scripts/orchestra -q
