#!/usr/bin/env bash
# Гвардия «дедуп issue-create не выключается молча» (issue #1395).
#
# Класс: «не смог посмотреть» засчитывалось как «прошло». Единственным
# источником репозитория был `gh repo view`; он ходит в GraphQL и в агентских
# каналах штатно отвечает 403 — сверка на дубли при этом молча выключалась с
# одним `::warning::`. Тот же третий рубеж уже признан обязательным у гвардии
# пуша (#1096): «не смог посмотреть» ≠ «прошло».
#
# Цена измерена: #1385 и #1386 — байт-в-байт одинаковые задачи (sha256 тел
# совпадает), созданные с разницей в 7 секунд, обе висели в пуле открытыми.
#
# Носитель — scripts/lib/test_issue_create_repo_resolution.py: настоящий bash
# гоняет настоящий скрипт, отказ `gh repo view` воспроизводится настоящим
# ненулевым кодом возврата, третий источник — настоящим `git init` с настоящим
# remote. Текстовая проверка исходника доказала бы орфографию, а не поведение
# (класс #891/#893).
#
# Доказано мутациями — ИСПОЛНЕНО, не пересказано (числа в теле PR).
#
# Регистрируется каталогом (#749), не рукописным шагом repo-ci.yml —
# ci-guard-registration.sh замораживает список рукописных шагов.
set -euo pipefail
pip install --quiet pytest
python -m pytest scripts/lib/test_issue_create_repo_resolution.py -q
