#!/usr/bin/env python3
"""Номер задачи в тексте PR/issue — одно место правды (#187).

Класс проблемы: `f"#{n}" in text` и `line.split("#")` — сравнение подстрокой.
`#18` содержится в `#180`, `#181`, `#5180` — вылезло на живом прогоне orchestra
(33570081734): контракт спутал PR #185 (задача #182) с задачей #18. Число,
на которое ссылается `#N`, обязано иметь границу с обеих сторон: слева не
цифра (иначе `#18` внутри `#5180`), справа не цифра (иначе `#18` внутри
`#180`).

Импорт — importlib по файлу (паттерн claim_task/review_labels): скрипты
запускаются как файлы, не как пакет.

Два разных вопроса, две разные группы функций — не путать (#259, живой
замер: ai_review.py:353 отвечал на вопрос «какая задача упомянута первой в
прозе» там, где нужен ответ на «какая задача у этого PR», и путал #253 с
#120, #248 с #119, #247 с #43, #263 с #4):

  «Какая задача у этого PR» (узкая, для решений вида «этот PR закрывает
  задачу N», «контекст ревью», «занята ли задача») — `resolve_pr_task`,
  единственный источник — имя agent-ветки (`task_from_branch`). Решение
  владельца 2026-09-06 (#394, вторым заходом после `pr_task_candidates`):
  тело PR для этого вопроса не читается вообще — ни первой строкой, ни
  каким-либо иным способом. `None` — «у PR нет задачи из пула» (боты, PR без
  agent-ветки), ожидаемый ответ, не ошибка. PR, чья ветка называет уже
  закрытую задачу (докрытие/реворк), не «переориентируется» неявным чтением
  тела — заводится новая ветка `scripts/git/task-branch <M>-<slug>` на новый
  номер, см. design.md contract-task-from-branch.

  «Упоминает ли текст задачу» (широкая, ЛЮБОЕ вхождение `#N`) —
  `extract_task_refs`/`references_task`. Годится только там, где широта
  осознанна и названа в докстринге места вызова: `reap_stale`/
  `unhealthy_pulls`/`after_merge` в scheduler.py (не потерять живой PR или
  не снять чужой замок — ошибиться в сторону «не трогать» там дешевле, чем
  в сторону «занята»). Новый вызов этой пары ВНЕ scheduler.py — красный
  тест `scripts/lib/test_task_ref_usage_guard.py`, не только докстринг.

Функции `declared_tasks`/`declares_task` (декларация — первая непустая
строка тела, правило #251/#312) удалены 2026-09-06 вместе с
`pr_task_candidates`: решение владельца убрало тело PR как источник для
вопроса «какая задача у PR» целиком, а других вызывающих у этой пары не
было. История класса (подстрочное совпадение #187, перенос строки прозы
#251, HTML-комментарий шаблона #312) — в git-истории этого файла и в
openspec/changes/contract-task-from-branch/proposal.md, не потеряна, просто
больше не активный код.
"""

import re

# Слева: не должно быть цифры прямо перед `#`-числом (запрещает `5#18`→`518`
# и `#5` перед `180`, т.е. случай "числовой хвост предыдущего номера слипся").
# Справа: не должно быть цифры сразу после числа (запрещает `#180` матчить `#18`).
_TASK_REF_RE = re.compile(r"(?<!\d)#(\d+)(?!\d)")


def extract_task_refs(text: str) -> list[int]:
    """Все номера задач `#N` из текста, с границей числа с обеих сторон.

    Порядок — как в тексте, дубликаты не схлопываются (вызывающий код решает
    сам, нужна ли уникальность и первый элемент).
    """
    if not text:
        return []
    return [int(match.group(1)) for match in _TASK_REF_RE.finditer(text)]


def references_task(text: str, task_number: int) -> bool:
    """Упоминает ли текст задачу `#task_number` — без ложных срабатываний на
    `#<task_number><ещё цифры>` или `<ещё цифры><task_number>` (класс #187)."""
    return task_number in extract_task_refs(text)


# ── Резолвер «PR → задача» (#259, #394) — одно место правды, один источник ───
#
# Единственный источник — имя ветки `agent/<N>-<slug>`: её создаёт ТОЛЬКО
# `scripts/git/task-branch` (enforced-правило репозитория, гвардия
# .githooks/pre-commit), номер в ней подделать случайно нельзя. Тело PR для
# этого вопроса не читается вовсе — ни первой строкой, ни GitHub-связью
# closes/fixes (closingIssuesReferences), ни любым другим способом.
#
# Раньше здесь стояли ещё два запасных источника — оба сняты решением
# владельца 2026-09-06:
#
#   closingIssuesReferences — формальная связь GitHub PR↔issue. Проверено
#   фактом: живой GraphQL-запрос по последним 8 слитым PR репозитория вернул
#   пустой список у каждого (Closes/Fixes/Resolves запрещены contract_check.py
#   — GitHub нечего связывать формально). Источник никогда не был заполнен и
#   ни разу не вызывался с реальным значением (только в тестах) — снят как
#   мёртвый, а не как нежелательный.
#
#   Декларация первой строкой тела (`declared_tasks`) — держалась ради
#   переориентации в реворке: если ветка называла уже закрытую задачу, а
#   тело первой строкой объявляло новую, резолвер брал её из тела
#   (`pr_task_candidates`, #394, первый заход). Владелец отменил это без
#   исключений: «номер задачи берётся ТОЛЬКО из имени ветки… тело PR не
#   читается вообще». PR, чья ветка называет закрытую задачу, не
#   переориентируется неявно — заводится НОВАЯ ветка `scripts/git/task-branch
#   <M>-<slug>` на новый номер (живые PR на 2026-09-06, требуют новой ветки:
#   #388, #384, #359, #167 — см. proposal.md contract-task-from-branch).
#
# Проза по всему телу (extract_task_refs) как источник НЕ использовалась и не
# используется: это была ошибка ai_review.py:353 (см. докстринг модуля).

_BRANCH_TASK_RE = re.compile(r"^agent/(\d+)-")


def task_from_branch(branch: str) -> int | None:
    """Номер задачи из имени agent-ветки `agent/<N>-<slug>` — единственный
    источник резолвера (см. блок выше). `None`, если ветка не этой формы
    (ручной пуш, боты вроде dependabot — «задачи нет», а не ошибка)."""
    if not branch:
        return None
    match = _BRANCH_TASK_RE.match(branch)
    return int(match.group(1)) if match else None


def resolve_pr_task(pull: dict) -> int | None:
    """Задача, которой принадлежит PR — единственная точка входа для этого
    вопроса (см. докстринг модуля и блок выше). `None` — «у PR нет задачи»,
    ожидаемый ответ для ботов (dependabot) и PR без agent-ветки, не ошибка.

    `pull` — объект PR из `gh api repos/.../pulls/N` (нужен только
    `head.ref`; тело не читается вовсе, см. блок выше)."""
    branch = ((pull.get("head") or {}).get("ref")) or ""
    return task_from_branch(branch)
