#!/usr/bin/env python3
"""Категория сигнала владельцу — одно место правды на три отправителя (#1461).

Класс, названный одной фразой: **всё, что уходит владельцу, сыплется одним
потоком, и категория сообщения не выражена машинно нигде — только эмодзи
внутри текста, который каждый отправитель собирает сам.**

Замер отправителей на 2026-09-22 (не оценка на глаз — вызовы пересчитаны):

    scripts/orchestra/pulse_guard.py::send_telegram     8 вызовов
    scripts/orchestra/scheduler.py                      1 вызов
    scripts/orchestra/apply_owner_decision.py           1 вызов
    scripts/worker/task.sh::telegram_report             bash, отдельный
    cf-worker/src/harness.ts::#telegramApi              TypeScript, третий

Три несвязанных отправителя на трёх языках. Прикрутить маршрутизацию к
каждому по отдельности значило бы завести три копии таблицы «категория →
адрес» — отложенный рецидив, а не осторожность (AGENTS.md, «Одно место
правды»).

## Почему категория — это не эмодзи в тексте

Эмодзи читает человек, а адресовать сообщение нужно машине. Сегодня адрес —
видимый префикс; когда подтвердятся треды в личке (Bot API: `message_thread_id`
в приватных чатах, требует режима тем у бота через @BotFather), тот же
идентификатор категории станет номером темы. Точки отправки при этом не
меняются вовсе: они называют КАТЕГОРИЮ, а не адрес.

Разделение намеренное: `category_prefix` отвечает «как показать», будущий
резолвер темы — «куда положить». Смешать их значило бы переписывать десять
точек отправки на каждое изменение доставки.

## Почему нет категории «прочее»

Отправка без категории обязана быть невозможной, а не сваливаться в «прочее»:
молчаливое «прочее» — это ровно нынешнее состояние, только под новым именем.
Поэтому `category` у отправителей — обязательный именованный аргумент, а
`category_prefix` на незнакомом идентификаторе падает громко.

Запуск: python scripts/lib/alert_category.py   (печатает таблицу категорий)
Тесты:  python -m pytest scripts/lib/test_alert_category.py -q
"""

# --- console_utf8 bootstrap (класс: печать кириллицы валит encoding на Windows, issue #723) ---
import importlib.util
from pathlib import Path
_console_utf8_spec = importlib.util.spec_from_file_location(
    "console_utf8", Path(__file__).resolve().parent / "console_utf8.py")
_console_utf8_spec.loader.exec_module(importlib.util.module_from_spec(_console_utf8_spec))
# --- конец console_utf8 bootstrap ---

import sys

# Четыре категории — решение владельца 2026-09-22. Набор выведен из замера
# отправителей выше, а не придуман: каждая покрывает реально существующие
# точки отправки, пустых категорий нет.
#
# Порядок — от «требует человека» к «к сведению»: он же задаёт порядок тем,
# когда треды включатся, и порядок в сводке, если не включатся.
OWNER_DECISION = "decision"
BREAKAGE = "breakage"
PIPELINE = "pipeline"
INFRA = "infra"

# id → (видимый префикс, человеческое имя, что сюда относится).
# Третье поле — не украшение: оно единственное место, где написано, КАК
# выбирать категорию, и читает его тот, кто добавляет новую точку отправки.
CATEGORIES: dict[str, tuple[str, str, str]] = {
    OWNER_DECISION: (
        "🙋",
        "Решение владельца",
        "ждёт действия человека и без него не поедет: варианты с инлайн-кнопками, "
        "задача с меткой waiting:owner, отказ применить присланное решение",
    ),
    BREAKAGE: (
        "🔴",
        "Поломка",
        "сломалось и само не починится: хранилище журнала не отвечает, пульс не "
        "тикает, обязательная проверка красная по настоящей причине",
    ),
    PIPELINE: (
        "⚙️",
        "Конвейер",
        "ход работы: слияния, диспатч воркера, пауза предохранителя и возврат, "
        "открытые и слитые PR, исход прогона воркера",
    ),
    INFRA: (
        "🏗",
        "Инфраструктура",
        "деплой и откаты, квоты и лимиты (DO, GitHub API, провайдеры), "
        "безопасность — алерты Dependabot, защита ветки",
    ),
}

# Порядок объявления — он же порядок показа. dict в Python сохраняет порядок
# вставки, но полагаться на это молча нельзя: следующий читатель не обязан
# знать, что порядок значим, поэтому он назван отдельно и проверяется тестом.
CATEGORY_ORDER: tuple[str, ...] = (OWNER_DECISION, BREAKAGE, PIPELINE, INFRA)


class UnknownAlertCategory(ValueError):
    """Категория не из реестра. Отдельный класс, чтобы вызывающий не путал
    её с прочими ValueError: лечится добавлением категории в CATEGORIES
    (и в две другие языковые копии — их сверяет
    scripts/lib/test_alert_category_sync.py), а не подстановкой «прочее»."""


def category_prefix(category: str) -> str:
    """Видимый префикс сигнала: «🙋 Решение владельца».

    Отдельно от текста сообщения намеренно: текст собирают десять разных
    мест, и вклеивать туда категорию руками значило бы завести десять
    способов её написать."""
    if category not in CATEGORIES:
        raise UnknownAlertCategory(
            f"категория {category!r} не объявлена в alert_category.CATEGORIES. "
            f"Известны: {', '.join(CATEGORY_ORDER)}. Новая категория заводится в "
            f"реестре (и в cf-worker/src/config.ts + scripts/lib/alert_category.sh — "
            f"их сверяет test_alert_category_sync.py), а не подстановкой «прочее»"
        )
    emoji, title, _ = CATEGORIES[category]
    return f"{emoji} {title}"


def decorate(category: str, text: str) -> str:
    """Текст сигнала с видимой категорией первой строкой.

    Почему строкой, а не в начало первой строки текста: тексты сигналов уже
    начинаются со своих эмодзи (🚨, ✅, ⏸️), и склейка дала бы два эмодзи
    подряд без пробела смысла. Отдельная строка читается и остаётся местом,
    куда встанет ссылка на тему, когда темы включатся."""
    return f"{category_prefix(category)}\n{text}"


def main() -> int:
    for index, category in enumerate(CATEGORY_ORDER, start=1):
        emoji, title, what = CATEGORIES[category]
        print(f"{index}. {emoji} {title} ({category})\n   {what}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
