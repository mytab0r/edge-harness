#!/usr/bin/env python3
"""Классификация исхода вызова морды dsh-edge — одно место правды (#1433).

Класс, оплаченный тремя авариями за одни сутки 2026-09-21/22: каждый вызывающий
классифицировал отказ СВОИМ рукописным правилом, и ни один не знал о других.

    scheduler.py:2704   if "session-not-found" in str(error):   # архив
    scheduler.py:2848   if "HTTP 404" in str(error):            # заметки
    (+ SessionFormatUnsupportedMigrationError — добавлено #1430, третьей копией)

`_archive_with_opener` не знал про неподдерживаемый формат сессии,
`append_session_notes` не знал про `session-not-found`, и обе трактовали «всё
остальное» как сломанную возможность. Итог каждый раз одинаковый: красный
прогон orchestra, который `pulse_guard` читает как «пульсы пропадали», и
владельцу уходит «конвейер мёртв» при живом конвейере.

**Исходов не два, а четыре**, и лечатся они по-разному:

1. успех;
2. TERMINAL — терминальный исход КОНКРЕТНОГО элемента: повтор не поможет
   никогда (сессии нет; формат не мигрируется). Строка отчёта, прогон зелёный;
3. BROKEN — возможность сломана временно: повтор поможет (суточная квота DO
   сбрасывается в 00:00 UTC, сеть, таймаут). Красный прогон, сигнал;
4. потеря факта (метку поставить не удалось) — вне этого модуля: он про исход
   ВЫЗОВА морды, а не про состояние нашей очереди.

**Умолчание — BROKEN, и это выбор, а не случайность.** Незнакомый отказ
громче, чем надо, дешевле незнакомого отказа тише, чем надо: первый стоит
лишнего сигнала, второй — молчаливого накопления. Тот же fail-safe, что у
`active_run_kind` в `scripts/gh/wake_orchestra.sh` (#1408).

Добавить новый терминальный отказ = дописать строку в `TERMINAL_FAILURES`
ниже. Все потребители начинают трактовать его одинаково, без правки их кода —
ровно это и проверяет `test_adding_a_marker_reaches_every_caller_at_once`.
"""

# --- console_utf8 bootstrap (класс: печать кириллицы валит encoding на Windows, issue #723) ---
import importlib.util
from pathlib import Path
_console_utf8_spec = importlib.util.spec_from_file_location(
    "console_utf8", Path(__file__).resolve().parent / "console_utf8.py")
_console_utf8_spec.loader.exec_module(importlib.util.module_from_spec(_console_utf8_spec))
# --- конец console_utf8 bootstrap ---

TERMINAL = "terminal"
BROKEN = "broken"

# Маркер отказа → человекочитаемая причина. Причина живёт ЗДЕСЬ, а не
# переписывается в каждой строке отчёта: иначе два вызывающих объяснят один и
# тот же отказ по-разному, и читатель решит, что это разные отказы.
#
# Каждая строка — оплаченный случай, а не предположение:
# Терминальные исходы делятся ещё раз, и это различение реальное, а не
# украшение (поймано тестом test_append_session_notes_session_not_found_...):
#
#   * НОРМА — ничего не потеряно, потому что нечего было терять. Задача без
#     прогона воркера (ручной PR, работа агента в чате) сессии в морде не
#     имеет вовсе. Печатать строку на каждую такую задачу — шум;
#   * ПОТЕРЯ — работа была, и она не доедет никогда. Заметка в сессию с
#     немигрируемым форматом не попадёт ни при каком повторе; молчать об этом
#     нельзя, читатель обязан узнать номер и причину.
#
# Оба «повтор не поможет», но отчёт у них разный, поэтому признак живёт рядом
# с маркером, а не в голове у каждого вызывающего.
LOSS = "loss"
NORMAL = "normal"

TERMINAL_FAILURES: dict[str, tuple[str, str]] = {
    # Архив (#119): RPC морды отвечает так, когда сессии раннера нет вовсе —
    # задача без прогона воркера (ручной PR, работа агента в чате).
    "session-not-found": ("сессии раннера в морде нет", NORMAL),
    # Заметки-итоги (#480): тот же смысл, другой транспорт — ingest отвечает
    # кодом HTTP, а не текстом RPC.
    "HTTP 404": ("сессии раннера в морде нет", NORMAL),
    # #1430, живой прогон 35647962282: поле `truncated` в data записал наш же
    # стример (дефект #1404, фикс #1405 `8b46e8d4` убрал его из НОВЫХ
    # событий). Уже записанные сессии остались в хранилище морды такими, какие
    # есть, и апстримная миграция v0→v1 будет отказывать всегда: формат сам не
    # изменится.
    # Одного маркера довольно: `SessionFormatUnsupported` — ПРЕФИКС
    # `SessionFormatUnsupportedMigrationError`, и второй записью список только
    # выглядел бы полнее (замечание ai-review PR #1431). Совпадение здесь
    # подстрочное, поэтому короткий префикс покрывает и длинную форму, и любую
    # будущую `SessionFormatUnsupported*`.
    # Формулировка причины — из #1444 (слит в main, одно место правды — здесь):
    # формат в хранилище сам не изменится, повтор бессмысленен;
    # `SessionPersistenceCorruptionError` (повреждение, а не честный отказ
    # миграции, ADR 0027) сюда НЕ входит и остаётся сломанной возможностью.
    "SessionFormatUnsupported":
        ("морда отказывается мигрировать формат сессии — формат в хранилище "
         "сам не изменится", LOSS),
}


def classify(error: object) -> str:
    """TERMINAL или BROKEN по СОДЕРЖАНИЮ отказа, а не по коду ответа.

    По коду различить нельзя принципиально: и «формат не мигрируется», и
    «квота исчерпана» приходят как `HTTP 500 Internal runtime error`, а
    лечатся противоположно — второе ждёт повтора, первое не дождётся никогда.
    """
    text = str(error)
    return TERMINAL if any(marker in text for marker in TERMINAL_FAILURES) else BROKEN


def is_terminal(error: object) -> bool:
    return classify(error) == TERMINAL


def terminal_reason(error: object) -> str | None:
    """Человекочитаемая причина терминального исхода — для строки отчёта.

    None на нетерминальном отказе: вызывающий обязан различать, а не печатать
    пустую причину рядом со сломанной возможностью."""
    text = str(error)
    for marker, (reason, _kind) in TERMINAL_FAILURES.items():
        if marker in text:
            return reason
    return None


def is_loss(error: object) -> bool:
    """Терминальный исход, при котором РАБОТА ПОТЕРЯНА (в отличие от «нечего
    было терять»). Только о таком обязана появиться строка в отчёте: иначе
    отчёт заполняется нормой — задачами без прогона воркера — и настоящая
    потеря в нём тонет."""
    text = str(error)
    for marker, (_reason, kind) in TERMINAL_FAILURES.items():
        if marker in text:
            return kind == LOSS
    return False
