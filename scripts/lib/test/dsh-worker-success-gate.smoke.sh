#!/usr/bin/env bash
# Гвардия класса #876 (живой инцидент — прогон worker.yml 34498185823, задача
# #140, 2026-09-10): worker/task.sh отрапортовал «🤖 Автономный воркер
# справился (провайдер: ?)», хотя dsh упал на ВСЕХ провайдерах цепочки этого
# прогона (rc=1, WORKER_CHAIN_PROVIDER пусто) — критерий успеха смотрел
# ТОЛЬКО на факт «PR по ветке существует» (pr_outcome.py), а PR #395
# существовал с прошлого прогона (2026-09-05).
#
# Плюс регрессия #878 (задача #935, восемь провалов подряд 2026-09-11,
# идентичная сигнатура «... существует, но не доказывает работу этого
# прогона: новых коммитов в ветке за этот прогон нет» на разных задачах):
# #878 сам мерил «работу этого прогона» ТОЛЬКО по локальному HEAD воркера
# (линкованный git worktree), а агент, обходя файловую песочницу dsh (её
# запрет на запись в общий commondir — дословно из логов, см. комментарий
# у dsh_worker_run_is_success в dsh-ci.sh), пушит из отдельного клона
# напрямую в origin — локальный HEAD не двигается, хотя работа доезжает.
#
# Тестирует dsh_worker_run_is_success (scripts/lib/dsh-ci.sh) — ЕДИНСТВЕННОЕ
# место правды критерия «работа этого прогона доказана» (rc==0 И непустой
# провайдер И новый коммит — локально ИЛИ на origin), от которого
# worker/task.sh требует конъюнкции с pr_outcome.py (существование PR), а не
# решает по одному ему.
#
# Мутация, которой доказана проверка (см. НИЗ файла): если
# dsh_worker_run_is_success игнорирует rc/provider/sha и возвращает 0 всегда
# (старое поведение, эквивалент «единственный критерий — pr_outcome_rc»),
# сценарий 2 (живая форма инцидента #876) обязан покраснеть. Если снять
# ТОЛЬКО origin-часть признака #3 (вернуть чистое сравнение локальных SHA),
# сценарий 7 (регрессия #878 — origin ушёл вперёд, локально тихо) обязан
# покраснеть отдельно — это и есть мутация, доказывающая именно фикс #935,
# не фикс #876.
#
# Запуск: bash scripts/lib/test/dsh-worker-success-gate.smoke.sh
set -euo pipefail

SMOKE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SMOKE_DIR/../../.." && pwd)"

fail() { echo "::error::SMOKE(worker-success-gate): $*" >&2; exit 1; }

# shellcheck source=scripts/lib/dsh-ci.sh
source "$REPO/scripts/lib/dsh-ci.sh"

SAME_SHA="7d587bcfaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
NEW_SHA="1234567890bbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"
# SHA слитого коммита ветки на origin (прод-форма: например голова
# agent/407-worker после мержа PR #412, живой прогон 34550467839).
MERGED_SHA="fe0175a117057e1ec806b04782d06c9649e5689e"

# ── 1) успех: rc=0, провайдер назван, есть новый коммит локально ─────────────
if dsh_worker_run_is_success 0 "GLM" "$SAME_SHA" "$NEW_SHA" "$SAME_SHA" "$SAME_SHA"; then
  echo "SMOKE(worker-success-gate): 1) rc=0 + провайдер + новый коммит локально -> успех — ок"
else
  fail "1) настоящий успех этого прогона обязан пройти гейт"
fi

# ── 2) живая форма инцидента #876: rc=1, провайдер пуст, НИЧЕГО не сдвинулось,
# ни локально, ни на origin (PR #395 существовал с прошлого прогона) ─────────
if dsh_worker_run_is_success 1 "" "$SAME_SHA" "$SAME_SHA" "$SAME_SHA" "$SAME_SHA"; then
  fail "2) живая форма инцидента #876 обязана провалить гейт (rc=1, провайдер пуст, коммитов нет)"
else
  echo "SMOKE(worker-success-gate): 2) rc=1 + пустой провайдер + предсуществующая ветка -> провал гейта — ок"
fi

# ── 3) rc=0 без имени провайдера (защитный случай — рассинхрон переменных) ───
if dsh_worker_run_is_success 0 "" "$SAME_SHA" "$NEW_SHA" "$SAME_SHA" "$SAME_SHA"; then
  fail "3) пустой провайдер при rc=0 — противоречие, обязано быть провалом гейта"
else
  echo "SMOKE(worker-success-gate): 3) rc=0 но провайдер не назван -> провал гейта — ок"
fi

# ── 4) rc=0, провайдер назван, но НИЧЕГО не сдвинулось (нет новых коммитов
# ни локально, ни на origin) — предсуществующий PR, этот прогон его не тронул
if dsh_worker_run_is_success 0 "GLM" "$SAME_SHA" "$SAME_SHA" "$SAME_SHA" "$SAME_SHA"; then
  fail "4) rc=0 без единого нового коммита (локально и на origin) — не доказательство работы этого прогона"
else
  echo "SMOKE(worker-success-gate): 4) rc=0 + провайдер, но ничего нигде не менялось, PR предсуществовал -> провал гейта — ок"
fi

# ── 5) rc!=0, провайдер назван (не должно случаться, но гейт обязан быть строг) ─
if dsh_worker_run_is_success 1 "GLM" "$SAME_SHA" "$NEW_SHA" "$SAME_SHA" "$SAME_SHA"; then
  fail "5) rc!=0 не может быть успехом, даже если провайдер назван"
else
  echo "SMOKE(worker-success-gate): 5) rc!=0 -> провал гейта независимо от провайдера — ок"
fi

# ── 6) #880: DSH_WORKER_RUN_GATE_GAPS — одно место правды на текст причины,
# не вторая копия трёх условий в task.sh. Живая форма инцидента #876
# (сценарий 2) обязана назвать ВСЕ три несработавших конъюнкта; успех —
# оставить переменную пустой.
dsh_worker_run_is_success 1 "" "$SAME_SHA" "$SAME_SHA" "$SAME_SHA" "$SAME_SHA" || true
case "$DSH_WORKER_RUN_GATE_GAPS" in
  *"кодом 1"*"ни один провайдер"*"новых коммитов"*) ;;
  *) fail "6) DSH_WORKER_RUN_GATE_GAPS обязан назвать все три несработавших конъюнкта живого инцидента: '$DSH_WORKER_RUN_GATE_GAPS'" ;;
esac
echo "SMOKE(worker-success-gate): 6) DSH_WORKER_RUN_GATE_GAPS называет все несработавшие конъюнкты — ок"

dsh_worker_run_is_success 0 "GLM" "$SAME_SHA" "$NEW_SHA" "$SAME_SHA" "$SAME_SHA" || true
[ -z "$DSH_WORKER_RUN_GATE_GAPS" ] \
  || fail "6b) успех обязан оставить DSH_WORKER_RUN_GATE_GAPS пустым, получено: '$DSH_WORKER_RUN_GATE_GAPS'"
echo "SMOKE(worker-success-gate): 6b) успех оставляет DSH_WORKER_RUN_GATE_GAPS пустым — ок"

# ── 7) регрессия #878 (задача #935): origin ушёл вперёд, ЛОКАЛЬНЫЙ HEAD не
# двигался — агент обошёл файловую песочницу dsh отдельным клоном и запушил
# напрямую в origin (живой пример: PR #412, прогон 34550467839, локальные
# WORKER_BRANCH_START_SHA/END_SHA совпали, а origin ушёл на MERGED_SHA). До
# фикса #935 такой прогон кричал «новых коммитов в ветке за этот прогон
# нет», хотя коммит есть — просто на origin, не локально. Обязан быть УСПЕХ.
if dsh_worker_run_is_success 0 "GLM" "$SAME_SHA" "$SAME_SHA" "$SAME_SHA" "$MERGED_SHA"; then
  echo "SMOKE(worker-success-gate): 7) origin ушёл вперёд, локальный HEAD не двигался -> успех — ок (регрессия #878 не возвращается)"
else
  fail "7) origin ветки сдвинулся за этот прогон (обход песочницы, PR слит) — это обязано быть доказательством работы, гейт не должен требовать ИМЕННО локального сдвига"
fi

# ── 8) ничего нигде не менялось, PR предсуществовал (та же форма, что 2/4, но
# отдельным сценарием — именно эта форма и была регрессией #878 наоборот:
# фикс НЕ имеет права снова превратить предсуществующий нетронутый PR в
# успех только потому, что появился origin-признак) ──────────────────────────
if dsh_worker_run_is_success 0 "GLM" "$SAME_SHA" "$SAME_SHA" "$MERGED_SHA" "$MERGED_SHA"; then
  fail "8) ничего нигде не менялось (ни локально, ни на origin) — предсуществующий PR не должен становиться успехом"
else
  echo "SMOKE(worker-success-gate): 8) ничего нигде не менялось, PR предсуществовал -> провал гейта — ок"
fi

# ── 9) PR слит ЭТИМ прогоном: origin ветки продвинулся ДО sha слитого
# коммита (delete_branch_on_merge=false в этом репозитории — ветка не
# удаляется, её голова просто становится слитым коммитом), локальный чекаут
# воркера не двигался. Обязан быть УСПЕХ — тот же факт, что и в 7, отдельный
# сценарий по прямому требованию: «PR слит этим прогоном» — успех.
if dsh_worker_run_is_success 0 "GLM" "$SAME_SHA" "$SAME_SHA" "$NEW_SHA" "$MERGED_SHA"; then
  echo "SMOKE(worker-success-gate): 9) PR слит этим прогоном (origin продвинулся до слитого коммита) -> успех — ок"
else
  fail "9) PR, слитый этим прогоном (origin продвинулся), обязан проходить гейт как успех"
fi

# ── 10) текст гэпа называет ОБА факта дословно, не гадает — «алерт не
# гадает» (AGENTS.md): различает «ни один провайдер», «HEAD не сдвинулся» и
# состояние ветки на origin в одном сообщении.
dsh_worker_run_is_success 0 "GLM" "$SAME_SHA" "$SAME_SHA" "$MERGED_SHA" "$MERGED_SHA" || true
case "$DSH_WORKER_RUN_GATE_GAPS" in
  *"HEAD не сдвинулся"*"ветке на origin"*) ;;
  *) fail "10) текст гэпа обязан называть факт и по локальному HEAD, и по ветке на origin: '$DSH_WORKER_RUN_GATE_GAPS'" ;;
esac
echo "SMOKE(worker-success-gate): 10) текст гэпа называет оба факта (локальный HEAD и origin), не гадает — ок"

echo "SMOKE(worker-success-gate): критерий успеха воркера (#876/#878) держит все десять сценариев — гвардия зелёная"
