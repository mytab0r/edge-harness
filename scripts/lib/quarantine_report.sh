#!/usr/bin/env bash
# Состав карантина сессий в лог прогона (issue #1379).
#
# Патч 0007 (#1376) изолирует сессию, которую билд не может перевести в текущий
# формат: морда стартует, а запись остаётся как есть. Состав карантина при этом
# был недоступен прогону деплоя — `console.error` уходит в Workers-логи (Logpush
# не подключён), а таблица `dsh_edge_quarantined_sessions` живёт внутри Durable
# Object. Патч 0008 открывает состав маршрутом `GET /api/quarantine`, эта
# функция его читает и печатает.
#
# Почему отдельный файл, а не тело шага в YAML: шаг в YAML нечем проверить
# поведенчески. Здесь — одно место правды, которое зовут и деплой, и тест
# `scripts/lib/test_quarantine_report.py` (настоящий сервер, настоящий curl,
# настоящий jq; «недоступность» — закрытый порт, а не подменённая функция;
# AGENTS.md, «Заглушка внешнего инструмента — это пересказ»).
#
# Различение, ради которого задача заведена: «карантин пуст» и «состав
# прочитать не смогли» — РАЗНЫЕ исходы, и лечатся по-разному. Первый —
# штатное состояние, второй — отказ. Поэтому непрочитанный маршрут красит шаг,
# а непустой карантин — нет: иначе одна старая запись валила бы каждый деплой,
# ровно тот исход, против которого #1376 и делался.
#
# Подключение:
#   source "$GITHUB_WORKSPACE/scripts/lib/canary_http.sh"
#   source "$GITHUB_WORKSPACE/scripts/lib/quarantine_report.sh"
#   quarantine_report "$base" "$jar"
# Рассчитано на bash с `set -euo pipefail` (источник задаёт).

# Печатает состав карантина, прочитанный с базы $1 с cookie-jar $2.
# Возврат 0 — состав прочитан (пуст он или нет); возврат 1 — прочитать НЕ
# удалось, и это отказ, а не пустой карантин.
quarantine_report() {
  local base=$1 jar=$2
  local body count

  body=$(canary_http "Чтение карантина #1379" -b "$jar" "$base/api/quarantine") || {
    echo "::error::Маршрут /api/quarantine не ответил — состав карантина НЕ прочитан (отказ чтения, а не отсутствие карантина)" >&2
    return 1
  }

  # Тело обязано быть разбираемым JSON с массивом. Неразбираемый ответ — тот же
  # класс «не знаю», что и молчащий маршрут: 200 с HTML-страницей прокси не
  # имеет права выглядеть как пустой карантин.
  # `.quarantined | length` на теле БЕЗ поля даёт 0 (`null | length`), то есть
  # отсутствие поля выглядело бы как пустой карантин — тот самый silent-wrong,
  # против которого задача. Поэтому сначала тип, и только потом длина.
  # Поймано поведенческой гвардией, а не глазами.
  count=$(printf '%s' "$body" | jq 'if (.quarantined | type) == "array" then (.quarantined | length) else "нет-массива" end' 2>/dev/null) || {
    echo "::error::Ответ /api/quarantine не разбирается как {quarantined: [...]} — состав карантина НЕ прочитан (отказ чтения, а не отсутствие карантина)" >&2
    return 1
  }
  if [ -z "$count" ] || [ "$count" = "null" ] || [ "$count" = '"нет-массива"' ]; then
    echo "::error::В ответе /api/quarantine нет массива quarantined — состав карантина НЕ прочитан (отказ чтения, а не отсутствие карантина)" >&2
    return 1
  fi

  if [ "$count" -eq 0 ]; then
    echo "✅ карантин пуст: ни одна сессия не осталась непереведённой (прочитано с прода, а не предположено)"
    return 0
  fi

  echo "::warning::карантин непуст: $count сессия(й) не переведены в текущий формат и оставлены как есть (#1376)"
  printf '%s' "$body" | jq -r '.quarantined[] | "  • \(.id) — формат v\(.storedVersion), причина: \(.reason)"'
  return 0
}
